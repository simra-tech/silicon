#!/usr/bin/env python3
"""Write tb/r1_chip.sp (chip netlist of the full-chip testbench) and tb/views/ctrl_rtl.inc.tmpl (digital view).

r1_chip.sp is the design-intent connection of R1 at the top level: the instances and net names of the chip LVS
reference (lvs/make_top_cdl_e.py, try e) plus every connection that try e leaves pending (ADC, isense outputs,
safe taps and inputs, PGA and T2F level shifters, isense auto-zero and CM). Each pending connection is marked
'PENDING-IN-LAYOUT' in a comment; tb/README.md lists them. The pads are the PDK sg13g2_io SPICE cells of the
spec pin map (section 3); the supply pad cells are not instantiated (the board supplies drive the rails).
The block cells are resolved by one view include (views/sch.inc or views/pex.inc) and the digital macro by
views/ctrl_rtl.inc (generated per run from the template, because the d_cosim model needs the compiled RTL path).
usage: python3 gen_chip.py   (writes r1_chip.sp, views/ctrl_rtl.inc.tmpl and rtl/t10_top.v)
"""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
L = []
A = L.append
A("* r1_chip.sp -- R1 full-chip testbench netlist (track T10), generated by tb/gen_chip.py; do not edit")
A("* Top-level nodes: pads in upper case (spec section 3), internal nets as the chip LVS reference (lower case).")
A("* Needs: PDK models, sg13g2_io.spice, sg13g2_stdcell.spice, one block view (views/sch.inc), views/ctrl_rtl.inc.")
A("")
A("* ---------------- pads (PDK sg13g2_io cells; core side = pad terminal for the analog pads, as the chip CDL) ----")
for p in ("SIN_P", "SIN_N", "COS_P", "COS_N", "ISA_P", "ISA_N", "ISB_P", "ISB_N", "VDDA"):
    A("XP_%s %s padres_%s VDD VSS IOVDD IOVSS sg13g2_IOPadAnalog" % (p.lower(), p, p.lower()))
for p, n in (("CS_N", "cs_n_p2c"), ("MA_SCLK", "ma_sclk_p2c"), ("SDI", "sdi_p2c"), ("EN_STO_IN", "en_sto_in_p2c")):
    A("XP_%s %s %s VDD VSS IOVDD IOVSS sg13g2_IOPadIn" % (p.lower(), p, n))
for p, n in (("FAULT_N", "fault_n_c2p"), ("SLO_SDO", "slo_sdo_c2p")):
    A("XP_%s %s %s VDD VSS IOVDD IOVSS sg13g2_IOPadOut4mA" % (p.lower(), p, n))
for p, n in (("GATE_A", "gate_a_c2p"), ("GATE_B", "gate_b_c2p"), ("GATE_C", "gate_c_c2p")):
    A("XP_%s %s %s VDD VSS IOVDD IOVSS sg13g2_IOPadOut30mA" % (p.lower(), p, n))
A("")
A("* ---------------- analog blocks ----------------")
A("XU_BGR VDDA VSS vref_bg bgr_iptat pbias pcasc bgr_vbe bgr_dvbe r1_bgr")
A("* MODEL M6 (T10 finding R1): no block of record buffers vref_bg. r1_bgr has a source of about 180 kOhm; the")
A("* r1_safe string (252 kOhm) and the r1_isense pedestals load it to 0.22 V (run t10-diag-nodeset-b). Ideal unity")
A("* buffer with 10 Ohm output for the resistive loads (isense, safe). T2F and the ADC filter keep vref_bg (gate inputs).")
A("Evref_m6 vref_m6i VSS vref_bg VSS 1")
A("Rvref_m6 vref_m6i vref_l 10")
A("XU_BIAS VDDA VDD VSS pbias pcasc ib_afe_s1 ib_afe_s2 ib_afe_c1 ib_afe_c2 ib_is_a ib_is_b ib_sf_oa ib_sf_na "
  "ib_sf_ob ib_sf_nb ib_adc_ref por_n r1_bias")
A("XU_T2F VDDA VDD VSS pbias pcasc vref_bg t2f_en33 t2f_mode33 t2f_fout r1_t2f")
A("* PENDING-IN-LAYOUT: t2f en/mode level shifters u_ls_t2f0/1 are placed but not connected in try e")
A("XU_LS_T2F0 t2f_en t2f_en33 VDD VDDA VSS t10_ls")
A("XU_LS_T2F1 t2f_mode t2f_mode33 VDD VDDA VSS t10_ls")
A("* PENDING-IN-LAYOUT: PGA lines pga_c[3:0] -> u_ls_afe0..3 -> r1_afe c1..c4")
for k in range(4):
    A("XU_LS_AFE%d pga_c%d afe_c%d VDD VDDA VSS t10_ls" % (k, k, k + 1))
A("* PENDING-IN-LAYOUT: AFE outputs and vcm2 to the ADC")
A("XU_AFE SIN_P SIN_N COS_P COS_N souts_p souts_n soutc_p soutc_n vcm2 ib_afe_s1 ib_afe_s2 ib_afe_c1 ib_afe_c2 "
  "afe_c1 afe_c2 afe_c3 afe_c4 VDDA VSS r1_afe")
A("* PENDING-IN-LAYOUT: isense outputs (to the ADC and to r1_safe), vcm, az/azh")
A("XU_ISENSE ISA_P ISA_N ISB_P ISB_N outa_p outa_n outb_p outb_n vref_l vcm ib_is_a ib_is_b az_a azh_a az_b azh_b "
  "VDDA VDD VSS r1_isense")
taps = []
for i, c in enumerate(("oa", "na", "ob", "nb")):
    taps += ["tap_p%d" % (8 * i + k) for k in range(8)] + ["tap_n%d" % (8 * i + k) for k in range(8)]
A("* PENDING-IN-LAYOUT: safe comparator inputs outa_p/n, outb_p/n (try e lists them as diagnostics) and the 64 tap")
A("* inputs (ctrl 0.5 tap_p/tap_n; comparator i = 0 OC_A, 1 NEG_A, 2 OC_B, 3 NEG_B at [8i +: 8], bit 0 = LSB)")
A("XU_SAFE outa_p outa_n outb_p outb_n vref_l")
for i in range(4):
    A("+ " + " ".join(taps[16 * i:16 * i + 16]))
A("+ cmp_oc_a cmp_neg_a cmp_oc_b cmp_neg_b ib_sf_oa ib_sf_na ib_sf_ob ib_sf_nb VDDA VDD VSS r1_safe")
A("* oscillator enable held high by a tie cell (as try e)")
A("XU_TIE_OSC osc_en VDD VSS sg13g2_tiehi")
A("XU_OSC osc_en osc_trim0 osc_trim1 osc_trim2 osc_trim3 osc_trim4 osc_clk VDD VSS r1_osc")
A("* PENDING-IN-LAYOUT: the whole r1_adc (placeholder r1_adc_ph); pin list of the placeholder + cur_trk (testbench)")
A("XU_ADC adc_hold is_smp osc_clk adc_start adc_sel adc_valid_a")
A("+ " + " ".join("adc_raw_a%d" % k for k in range(14)))
A("+ adc_valid_b")
A("+ " + " ".join("adc_raw_b%d" % k for k in range(14)))
A("+ por_n souts_p souts_n soutc_p soutc_n vcm2 ib_adc_ref outa_p outa_n outb_p outb_n vcm VDDA VDD VSS vref_bg cur_trk r1_adc")
A("* gate path: ctrl gate_a/b/c (PWM AND gate_ok AND EN) -> r1_gate_lv -> 30 mA pads; gate_en tied to VDD (try e)")
A("XU_GATE pwm_a pwm_b pwm_c VDD gate_a_c2p gate_b_c2p gate_c_c2p VDD gate_vdda_nc VSS r1_gate_lv")
A("Rgate_vdda_nc gate_vdda_nc VSS 1e12")
A("")
A("* ---------------- digital macro + testbench master (view views/ctrl_rtl.inc) ----------------")
A("* XU_CTRL holds the r1_ctrl 0.5 RTL, the MODEL glue (rtl/r1_chip_dig.v) and the TESTBENCH master (rtl/t10_master.v)")
A("* in one d_cosim instance. The last 13 pins are testbench pins (master pad drives, stimulus selector, pad probes).")
# single source of the d_cosim port order: (spice net, verilog port, direction, kind)
#   kind: 'c' core 1.2 V logic, 'p' 3.3 V pad-level signal (master side)
IN = ([("osc_clk", "clk"), ("por_n", "por_n"), ("cs_n_p2c", "cs_n"), ("ma_sclk_p2c", "ma_sclk"), ("sdi_p2c", "sdi"),
       ("en_sto_in_p2c", "en_pad")]
      + [(n, "cmp[%d]" % b) for b, n in ((3, "cmp_neg_b"), (2, "cmp_oc_b"), (1, "cmp_neg_a"), (0, "cmp_oc_a"))]
      + [("t2f_fout", "t2f_clk"), ("adc_valid_a", "adc_valid_a")]
      + [("adc_raw_a%d" % k, "adc_raw_a[%d]" % k) for k in range(13, -1, -1)] + [("adc_valid_b", "adc_valid_b")]
      + [("adc_raw_b%d" % k, "adc_raw_b[%d]" % k) for k in range(13, -1, -1)])
IN_PAD = [("SLO_SDO", "slo_pad"), ("FAULT_N", "fault_pad"), ("GATE_A", "gate_a_pad")]
OUT = ([("slo_sdo_c2p", "slo_sdo"), ("fault_n_c2p", "fault_n"), ("pwm_a", "gate_a"), ("pwm_b", "gate_b"), ("pwm_c", "gate_c"),
        ("adc_hold", "adc_hold"), ("is_smp", "is_smp"), ("adc_start", "adc_start"), ("adc_sel", "adc_sel")]
       + [("tap_p%d" % k, "tap_p[%d]" % k) for k in range(31, -1, -1)] + [("tap_n%d" % k, "tap_n[%d]" % k) for k in range(31, -1, -1)]
       + [("az_a", "az_a"), ("azh_a", "azh_a"), ("az_b", "az_b"), ("azh_b", "azh_b")]
       + [("osc_trim%d" % k, "osc_trim[%d]" % k) for k in range(4, -1, -1)] + [("pga_c%d" % k, "pga_c[%d]" % k) for k in range(3, -1, -1)]
       + [("t2f_en", "t2f_en"), ("t2f_mode", "t2f_mode"), ("bias_en", "bias_en")]
       + [("seq_trka0", "trka0"), ("seq_trka1", "trka1"), ("seq_trkb0", "trkb0"), ("seq_trkb1", "trkb1"), ("seq_win", "win"),
          ("seq_lat", "lat")] + [("seq_stb%d" % k, "stb[%d]" % k) for k in range(13, -1, -1)]
       + [("seq_valid", "seq_valid"), ("cur_trk", "cur_trk")])
OUT_PAD = [("tbm_cs_n", "m_cs_n"), ("tbm_sclk", "m_sclk"), ("tbm_sdi", "m_sdi"), ("tbm_en", "m_en")]
OUT_SEL = [("tbs_a%d" % k, "sel_a[%d]" % k) for k in range(2, -1, -1)] + [("tbs_b%d" % k, "sel_b[%d]" % k) for k in range(2, -1, -1)]
pins = [n for n, _ in IN + IN_PAD + OUT + OUT_PAD + OUT_SEL] + ["VDD", "VSS"]
A("XU_CTRL")
for i in range(0, len(pins), 16):
    A("+ " + " ".join(pins[i:i + 16]))
A("+ r1_ctrl_top_tb")
A("Rbias_en_nc bias_en VSS 1e9")
open(os.path.join(HERE, "r1_chip.sp"), "w").write("\n".join(L) + "\n")

# digital view template (vvp path filled in per run by run_tb.py)
T = []
B = T.append
B("* views/ctrl_rtl.inc -- written by tb/run_tb.py from views/ctrl_rtl.inc.tmpl (template written by tb/gen_chip.py)")
B("* r1_ctrl revision 0.5 RTL + MODEL glue (rtl/r1_chip_dig.v) + TESTBENCH master (rtl/t10_master.v), root rtl/t10_top.v,")
B("* in one XSPICE d_cosim instance (Icarus shim ivlng), the G1 g1_top method. Core inputs: adc_bridge with a single")
B("* 0.6 V threshold (no unknown state, G1 numerical note 7); pad probes at 1.65 V. Core outputs: dac_bridge 0 / 1.2 V;")
B("* master pad drives 0 / 3.3 V. The seq_* outputs drive the global nodes of the r1_adc wrapper (views/sch.inc).")
sp = lambda l: [("p_" + n) for n, _ in l]
B(".subckt r1_ctrl_top_tb")
allp = sp(IN) + sp(IN_PAD) + sp(OUT) + sp(OUT_PAD) + sp(OUT_SEL) + ["vdd", "vss"]
for i in range(0, len(allp), 16):
    B("+ " + " ".join(allp[i:i + 16]))
B(".model t10_adcb adc_bridge(in_low=0.6 in_high=0.6 rise_delay=1e-12 fall_delay=1e-12)")
B(".model t10_adcp adc_bridge(in_low=1.65 in_high=1.65 rise_delay=1e-12 fall_delay=1e-12)")
B(".model t10_dacb dac_bridge(out_low=0 out_high=1.2 out_undef=0.6 input_load=1e-15 t_rise=250p t_fall=250p)")
B(".model t10_dacp dac_bridge(out_low=0 out_high=3.3 out_undef=1.65 input_load=1e-15 t_rise=1n t_fall=1n)")
B('.model t10_dig d_cosim simulation="ivlng" sim_args=["@VVP@"]')
d = lambda l: ["d_" + n for n, _ in l]
B("A_in [" + " ".join(sp(IN)) + "] [" + " ".join(d(IN)) + "] t10_adcb")
B("A_inp [" + " ".join(sp(IN_PAD)) + "] [" + " ".join(d(IN_PAD)) + "] t10_adcp")
B("A_dig [" + " ".join(d(IN) + d(IN_PAD)) + "] [" + " ".join(d(OUT) + d(OUT_PAD) + d(OUT_SEL)) + "] t10_dig")
B("* core outputs: dac_bridge to 0 / 1.2 V, then scaled by the macro supply (output high = VDD, also during the ramp)")
B("A_out [" + " ".join(d(OUT)) + "] [" + " ".join("q_" + n for n, _ in OUT) + "] t10_dacb")
for n, _ in OUT:
    B("B_%s p_%s vss V=v(q_%s)*v(vdd)/1.2" % (n, n, n))
B("A_sel [" + " ".join(d(OUT_SEL)) + "] [" + " ".join(sp(OUT_SEL)) + "] t10_dacb")
B("A_outp [" + " ".join(d(OUT_PAD)) + "] [" + " ".join(sp(OUT_PAD)) + "] t10_dacp")
B(".ends r1_ctrl_top_tb")
open(os.path.join(HERE, "views", "ctrl_rtl.inc.tmpl"), "w").write("\n".join(T) + "\n")

# d_cosim root module: same port order (inputs, then outputs; vectors MSB first)
def vports(l):
    out, seen = [], []
    for _, v in l:
        b = v.split("[")[0]
        if b not in seen:
            seen.append(b)
            w = [int(x.split("[")[1][:-1]) for _, x in l if x.split("[")[0] == b and "[" in x]
            out.append((b, (max(w), min(w)) if w else None))
    return out
V = []
C = V.append
C("// t10_top.v -- written by tb/gen_chip.py; do not edit. d_cosim root of the R1 full-chip testbench (track T10).")
C("// Port order = the d_cosim instance order of views/ctrl_rtl.inc (inputs, then outputs, vectors MSB first).")
C("`timescale 1ns/1ps")
decl = []
for l, dirn in ((IN, "input"), (IN_PAD, "input"), (OUT, "output"), (OUT_PAD, "output"), (OUT_SEL, "output")):
    for b, w in vports(l):
        decl.append("    %s wire %s%s" % (dirn, ("[%d:%d] " % w) if w else "", b))
C("module t10_top (")
C(",\n".join(decl))
C(");")
C("    wire tb_rst_n;")
C("    r1_chip_dig u_dig (.clk(clk), .por_n(por_n), .tb_rst_n(tb_rst_n), .cs_n(cs_n), .ma_sclk(ma_sclk), .sdi(sdi),")
C("        .en_pad(en_pad), .cmp(cmp), .t2f_clk(t2f_clk), .adc_valid_a(adc_valid_a), .adc_raw_a(adc_raw_a),")
C("        .adc_valid_b(adc_valid_b), .adc_raw_b(adc_raw_b), .slo_sdo(slo_sdo), .fault_n(fault_n), .gate_a(gate_a),")
C("        .gate_b(gate_b), .gate_c(gate_c), .adc_hold(adc_hold), .is_smp(is_smp), .adc_start(adc_start), .adc_sel(adc_sel),")
C("        .tap_p(tap_p), .tap_n(tap_n), .az_a(az_a), .azh_a(azh_a), .az_b(az_b), .azh_b(azh_b), .osc_trim(osc_trim),")
C("        .pga_c(pga_c), .t2f_en(t2f_en), .t2f_mode(t2f_mode), .bias_en(bias_en), .trka0(trka0), .trka1(trka1),")
C("        .trkb0(trkb0), .trkb1(trkb1), .win(win), .lat(lat), .stb(stb), .seq_valid(seq_valid), .cur_trk(cur_trk));")
C("    t10_master u_m (.slo_pad(slo_pad), .fault_pad(fault_pad), .gate_a_pad(gate_a_pad), .por_obs(por_n),")
C("        .m_cs_n(m_cs_n), .m_sclk(m_sclk), .m_sdi(m_sdi), .m_en(m_en), .tb_rst_n(tb_rst_n), .sel_a(sel_a), .sel_b(sel_b));")
C("endmodule")
open(os.path.join(HERE, "rtl", "t10_top.v"), "w").write("\n".join(V) + "\n")
print("written r1_chip.sp, views/ctrl_rtl.inc.tmpl, rtl/t10_top.v; d_cosim inputs %d outputs %d" %
      (len(IN) + len(IN_PAD), len(OUT) + len(OUT_PAD) + len(OUT_SEL)))
