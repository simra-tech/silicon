def interp_t(tab, t):
    ks = sorted(tab)
    if t <= ks[0]:
        return tab[ks[0]]
    for k0, k1 in zip(ks, ks[1:]):
        if t <= k1:
            return tab[k0] + (tab[k1] - tab[k0]) * (t - k0) / (k1 - k0)
    return tab[ks[-1]]


