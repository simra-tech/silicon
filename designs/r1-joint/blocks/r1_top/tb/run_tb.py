def sha(p):
    return hashlib.sha256(open(p, 'rb').read()).hexdigest()


def nodcn_io_lib(drop=('dantenna',)):
    """Deck-local copy of the PDK sg13g2_io.spi, cells renamed t10nd_<cell>, every dantenna instance removed
    (G1 run_top.py nodcn_io_lib, the documented G1 deviation; PDK file unchanged)."""
    lines = open(IOSPI).read().splitlines()
    cells = {l.split()[1] for l in lines if l.lower().startswith('.subckt')}
    out = ['* deck-local copy of %s: cells renamed t10nd_*, dantenna instances removed (tb/README.md, deviation D1)' % IOSPI]
    n = 0
    for l in lines:
        t = l.split()
        if not t or l.startswith('*'):
            continue
        if t[0].lower() == '.subckt':
            out.append(' '.join(['.subckt', 't10nd_' + t[1]] + t[2:]))
        elif t[0][0] in 'Xx':
            refs = [i for i, w in enumerate(t) if '=' not in w]
            ref = refs[-1]
            if t[ref] in drop:
                out.append('* removed (%s): ' % ('nodcn' if t[ref] == 'dantenna' else 'nodcp') + l)
                n += 1
                continue
            if t[ref] in cells:
                t[ref] = 't10nd_' + t[ref]
            out.append(' '.join(t))
        else:
            out.append(l)
    return out, n


def cpus_allowed():
    """CPU list of this process (the G1_CPUSET taskset of flow/run.sh); the record used a fixed 100-102 before."""
    try:
        for l in open('/proc/self/status'):
            if l.startswith('Cpus_allowed_list:'):
                return l.split()[1]
    except OSError:
        pass
    return os.environ.get('G1_CPUSET', 'unknown')


def subckt_names(path):
    return [l.split()[1].lower() for l in open(path) if l.lower().startswith('.subckt')]


def pwl(points):
    return 'PWL(' + ' '.join('%gu %g' % (t, v) for t, v in points) + ')'


def sel_expr(ch, levels):
    code = '(4*(v(tbs_%s2)>0.6)+2*(v(tbs_%s1)>0.6)+(v(tbs_%s0)>0.6))' % (ch, ch, ch)
    e = '0'
    for k in range(len(levels) - 1, -1, -1):
        if levels[k] != 0.0:
            e = '(%s==%d ? %g : %s)' % (code, k, levels[k], e)
    return e


