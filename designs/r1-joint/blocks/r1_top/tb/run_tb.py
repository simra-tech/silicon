#!/usr/bin/env python3
"""R1 full-chip functional testbench runner (track T10): ngspice 46 + XSPICE d_cosim (Icarus shim ivlng).

Run from the repository root through the pinned container (POSIX shell):

    G1_CPUSET=100-102; export G1_CPUSET; G1_RESULTS_ROOT=<G1_RESULTS_ROOT>; export G1_RESULTS_ROOT
    G1_WORKDIR=designs/r1-joint/blocks/r1_top/tb; export G1_WORKDIR
    flow/run.sh python3 run_tb.py --test 2 --run-id t10-enc-sch-a [--view sch] [--temp 27] [--corner tt]

One run = one deck: tb/r1_chip.sp (chip netlist, generated by gen_chip.py) + views/<view>.inc (block cells) +
views/ctrl_rtl.inc (digital macro, compiled per run) + the board and stimulus written here. The deck, the compiled
RTL, the log and the raw waveforms go to <G1_RESULTS_ROOT>/r1_top/tb/<run-id>/ (refused if it exists). The runner
writes run.json there and a copy in tb/runs/<run-id>/run.json (bulk path written as <G1_RESULTS_ROOT>), then calls
post_tb.py, which writes tb/results/<run-id>.json. Exit status: 0 only if ngspice completed and every criterion of
the test passed; 1 otherwise.
Swap to the extracted netlists: --view pex (views/pex.inc); nothing else changes.
"""
