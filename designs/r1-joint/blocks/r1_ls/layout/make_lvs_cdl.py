#!/usr/bin/env python3
"""Write r1_ls_lvs.cdl from the R1 netlist of record ../schematic/g1_ls_up_copy.spice (byte copy of the G1 netlist).

The KLayout LVS deck reads MOS devices as M elements. Each xschem line `XMxx d g s b model w= l= ng= m= mm_ok=1`
becomes `Mxx d g s b model w= l= ng= m=` (the X prefix of the instance name is dropped, mm_ok is dropped) and the
subckt is renamed g1_ls_up -> r1_ls. Same rewrite as the G1 file sim/netlist/g1_ls_up.cdl; compare with `diff`.
"""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
out = ['** R1_LS LVS reference, generated by make_lvs_cdl.py from schematic/g1_ls_up_copy.spice (subckt renamed g1_ls_up -> r1_ls)']
for line in open(os.path.join(HERE, '..', 'schematic', 'g1_ls_up_copy.spice')):
    line = line.strip()
    if not line or line.startswith('**'):
        continue
    if line.startswith('.subckt'):
        out.append(line.replace('.subckt g1_ls_up ', '.subckt r1_ls '))
    elif line.startswith('X'):
        tok = [t for t in line.split() if t != 'mm_ok=1']
        out.append(' '.join(['M' + tok[0][2:] if tok[0].startswith('XM') else tok[0]] + tok[1:]))
    else:
        out.append(line)
open(os.path.join(HERE, 'r1_ls_lvs.cdl'), 'w').write('\n'.join(out) + '\n')
print('wrote r1_ls_lvs.cdl')
