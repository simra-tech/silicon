#!/usr/bin/env python3
"""Generator of the r1_bias netlist (track T9, 2026-10-21).

r1_bias = bias distribution from the r1_bgr rails pbias/pcasc (one cascoded PMOS leg per consumer pin) plus the
power-on reset cell r1_por. All devices carry mm_ok=1 so the *_mismatch library sections act on them.

Usage: python3 gen_r1_bias.py [out.spice] [key=value ...]
"""
import sys

# Parameters of record (revision 1). Lengths in um.
P = dict(
    # distribution unit leg: mirror + cascode, both W_U/L_U (bgr unit leg is 10/4 at 4.2 uA -> 12/4 gives 5.0 uA)
    w_u=12.0, l_u=4.0,
    # POR replica reference: one bgr unit leg (10/4) into RA + RB (rppd w=1) + 4 npn13G2 units (as Q3 of r1_bgr)
    l_ra=45.9, l_rb=260.3,
    # VDDA divider, rhigh w=0.5 units of length l_dv: Rt1 = n_t1 units, Rt2 = n_t2 units (shorted when VDDA is good), Rb = n_b units
    l_dv=27.0, n_t1=16, n_t2=1, n_b=10,
    # comparator tail W (L 4), second-stage load W (L 4)
    w_tail=5.0, w_gl=2.5,
    # delay: n_st PMOS 0.5/4 in series from pbias, MIM w_c x w_c
    n_st=20, w_c=32.0,
    # local POR rail decoupling: PMOS gate capacitor w_cpl x w_cpl between pl and vdda (revision 1b)
    w_cpl=10.0,
    # experiment switches (dev-fix-20261021-a): replica leg on the local rail (1) or on the bgr rails (0);
    # MIM filter caps c_filt x c_filt um on vrh, vrl, tapa (0 = none)
    rep_local=0, c_filt=18.0,
    # por_raw pull-down, rhigh w = 0.5 um (revision 1d)
    l_rpd=735.0,
    # revision 2 (D20): unity-gain VREF buffer r1_vbuf. NMOS input pair (m_in units of w_in/l_in per side, common
    # centroid), PMOS mirror w_ld/l_ld, NMOS source-follower output m_o units w_o/l_o (drain at vdda), NMOS bias diode /
    # tail / sink from one r1_bias leg (vb_units units of 5.07 uA) in units of w_nb/l_nb (1 uA per unit at tt; sink
    # units w_s), compensation capacitor n_cc MIM plates of s_cc x s_cc um from x1 to vss.
    w_in=8.0, l_in=24.0, m_in=4, w_ld=5.0, l_ld=20.0, w_o=10.0, l_o=1.0,
    w_nb=5.0, l_nb=2.0, m_b=5, m_t=2, w_s=10.0, m_s=4, m_o=4, vb_units=1,
    s_cc=48.3, n_cc=2,
)

LEGS = [  # (pin, units) ; 1 unit = 12/4 um at ~5.0 uA (tt, 27 C)
    ("ib_afe_s1", 2), ("ib_afe_s2", 2), ("ib_afe_c1", 2), ("ib_afe_c2", 2),
    ("ib_is_a", 1), ("ib_is_b", 1),
    ("ib_sf_oa", 1), ("ib_sf_na", 1), ("ib_sf_ob", 1), ("ib_sf_nb", 1),
    ("ib_adc_ref", 1),
]


INT_LEGS = [("ibvb", "vb_units")]   # revision 2: internal leg into the r1_vbuf bias diode (not a pin)


def hvp(n, d, g, s, b, w, l, m=1):
    return "%s %s %s %s %s sg13_hv_pmos w=%gu l=%gu ng=1 m=%d mm_ok=1" % (n, d, g, s, b, w, l, m)


def hvn(n, d, g, s, b, w, l, m=1):
    return "%s %s %s %s %s sg13_hv_nmos w=%gu l=%gu ng=1 m=%d mm_ok=1" % (n, d, g, s, b, w, l, m)


def gen(p=None):
    p = dict(P, **(p or {}))
    o = []
    o.append("* r1_bias generated by gen_r1_bias.py " + " ".join("%s=%g" % (k, v) for k, v in sorted(p.items())))
    o.append("* Revision 2 (T9, 2026-10-26, D20: VREF buffer r1_vbuf, pins vref and vref_b, internal leg ibvb) on revision 1d (2026-10-21; 1b: local POR rail, 1c: 0.5 pF filters on vrh, vrl, tapa, 1d: pass-gate down-shifter). Supply VDDA 3.0-3.6 V (thick-oxide sg13_hv_*), VDD 1.2 V for the por_n output only.")
    o.append("")
    # ---------------------------------------------------------------- distribution leg
    o.append("* r1_bias_leg: one cascoded PMOS output leg from the r1_bgr rails, m units of w_u/l_u (mirror and cascode).")
    o.append("* The output sources current into the consumer's NMOS diode. Cascode body = its source (as in r1_bgr).")
    o.append(".subckt r1_bias_leg out pbias pcasc vdda m=1")
    o.append("XMP d pbias vdda vdda sg13_hv_pmos w=%gu l=%gu ng=1 m={m} mm_ok=1" % (p["w_u"], p["l_u"]))
    o.append("XMC out pcasc d d sg13_hv_pmos w=%gu l=%gu ng=1 m={m} mm_ok=1" % (p["w_u"], p["l_u"]))
    o.append(".ends r1_bias_leg")
    o.append("")
    # ---------------------------------------------------------------- inverter, nand (HV, VDDA domain)
    o.append(".subckt r1_por_inv a y vdda vss")
    o.append(hvp("XP", "y", "a", "vdda", "vdda", 1, 0.5))
    o.append(hvn("XN", "y", "a", "vss", "vss", 0.5, 0.5))
    o.append(".ends r1_por_inv")
    o.append(".subckt r1_por_nand2 a b y vdda vss")
    o.append(hvp("XP1", "y", "a", "vdda", "vdda", 1, 0.5))
    o.append(hvp("XP2", "y", "b", "vdda", "vdda", 1, 0.5))
    o.append(hvn("XN1", "y", "a", "x", "vss", 1, 0.5))
    o.append(hvn("XN2", "x", "b", "vss", "vss", 1, 0.5))
    o.append(".ends r1_por_nand2")
    o.append("")
    # ---------------------------------------------------------------- comparator
    o.append("* r1_por_cmp: open-loop two-stage comparator, PMOS input pair, tail from pbias (no cascode: headroom).")
    o.append("* o low <=> inp > inn. No feedback loop inside; the hysteresis loop is closed outside by switching the threshold.")
    o.append(".subckt r1_por_cmp inp inn o pbias vdda vss")
    o.append("* (pin pbias is connected to the local POR rail pl in r1_por)")
    o.append(hvp("XMT", "tail", "pbias", "vdda", "vdda", p["w_tail"], 4))
    o.append(hvp("XM1", "d1", "inp", "tail", "vdda", 8, 2))
    o.append(hvp("XM2", "d2", "inn", "tail", "vdda", 8, 2))
    o.append(hvn("XML1", "d1", "d1", "vss", "vss", 2, 4))
    o.append(hvn("XML2", "d2", "d1", "vss", "vss", 2, 4))
    o.append(hvn("XMG", "o", "d2", "vss", "vss", 1, 2))
    o.append(hvp("XMGL", "o", "pbias", "vdda", "vdda", p["w_gl"], 4))
    o.append(".ends r1_por_cmp")
    o.append("")
    # ---------------------------------------------------------------- Schmitt
    o.append("* r1_por_schmitt: 6-transistor Schmitt inverter on the delay capacitor (VDDA domain).")
    o.append(".subckt r1_por_schmitt a y vdda vss")
    o.append(hvp("XP1", "sp", "a", "vdda", "vdda", 1, 0.5))
    o.append(hvp("XP2", "y", "a", "sp", "vdda", 1, 0.5))
    o.append(hvp("XP3", "sp", "y", "vss", "vdda", 1, 0.5))
    o.append(hvn("XN1", "sn", "a", "vss", "vss", 0.5, 0.5))
    o.append(hvn("XN2", "y", "a", "sn", "vss", 0.5, 0.5))
    o.append(hvn("XN3", "sn", "y", "vdda", "vss", 0.5, 0.5))
    o.append(".ends r1_por_schmitt")
    o.append("")
    # ---------------------------------------------------------------- POR
    o.append("* r1_por: power-on reset. por_n (VDD domain) = 1 only when VDDA > 2.70 V (falling 2.60 V) AND VDD > 1.00 V")
    o.append("* (falling 0.95 V) have held for the delay (MIM charged by a PMOS stack from pbias; reset at once when either")
    o.append("* supply is low). Reference: replica of the r1_bgr output leg with a shorter R (vrh 1.00 V, tap vrl 0.95 V);")
    o.append("* it does not load the r1_bgr vref node.")
    o.append(".subckt r1_por vdda vdd vss pbias pcasc por_n")
    o.append("* replica reference")
    if p["rep_local"]:
        o.append(hvp("XMPR", "vrh", "pl", "vdda", "vdda", 10, 4))
    else:
        o.append(hvp("XMPR", "dr", "pbias", "vdda", "vdda", 10, 4))
        o.append(hvp("XMCR", "vrh", "pcasc", "dr", "dr", 10, 4))
    o.append("XRRA vrh vrl sub! rppd w=1u l=%gu m=1 b=0 mm_ok=1" % p["l_ra"])
    o.append("XRRB vrl vq sub! rppd w=1u l=%gu m=1 b=0 mm_ok=1" % p["l_rb"])
    for i in range(4):
        o.append("XQR_%d vq vq vss vss npn13G2 Nx=1 mm_ok=1" % i)
    o.append("* local bias rail pl (revision 1b): one cascoded bgr leg -> NMOS diode -> NMOS mirror -> PMOS diode pl,")
    o.append("* decoupled to vdda. Comparator tails, second-stage loads and the delay stack hang on pl, so their switching")
    o.append("* edges do not reach the r1_bgr pbias node (chain a/b: solver stalls in r1_bgr at every comparator edge).")
    o.append(hvp("XMPL", "dl", "pbias", "vdda", "vdda", 10, 4))
    o.append(hvp("XMCL", "nl", "pcasc", "dl", "dl", 10, 4))
    o.append(hvn("XNL", "nl", "nl", "vss", "vss", 4, 4))
    o.append(hvn("XNM", "pl", "nl", "vss", "vss", 4, 4))
    o.append(hvp("XPL", "pl", "pl", "vdda", "vdda", 10, 4))
    o.append(hvp("XCPL", "vdda", "pl", "vdda", "vdda", p["w_cpl"], p["w_cpl"]))
    o.append("* VDDA divider (rhigh units): vdda - Rt1 - na - Rt2 - tapa - Rb - vss; Rt2 shorted while VDDA is good")
    nodes = ["vdda"] + ["dt1_%d" % i for i in range(1, p["n_t1"])] + ["na"]
    k = 0
    for a, b in zip(nodes[:-1], nodes[1:]):
        o.append("XRT1_%d %s %s sub! rhigh w=0.5u l=%gu m=1 b=0 mm_ok=1" % (k, a, b, p["l_dv"])); k += 1
    nodes = ["na"] + ["dt2_%d" % i for i in range(1, p["n_t2"])] + ["tapa"]
    for i, (a, b) in enumerate(zip(nodes[:-1], nodes[1:])):
        o.append("XRT2_%d %s %s sub! rhigh w=0.5u l=%gu m=1 b=0 mm_ok=1" % (i, a, b, p["l_dv"]))
    nodes = ["tapa"] + ["db_%d" % i for i in range(1, p["n_b"])] + ["vss"]
    for i, (a, b) in enumerate(zip(nodes[:-1], nodes[1:])):
        o.append("XRB_%d %s %s sub! rhigh w=0.5u l=%gu m=1 b=0 mm_ok=1" % (i, a, b, p["l_dv"]))
    o.append(hvn("XHA", "na", "gooda", "tapa", "vss", 1, 0.5))
    o.append("* comparators: A = VDDA tap vs vrh; D = VDD vs refd (vrh while VDD is bad, vrl while it is good)")
    if p["c_filt"] > 0:
        for nd in ("vrh", "vrl", "tapa"):
            o.append("XCF_%s %s vss cap_cmim w=%gu l=%gu m=1 mm_ok=1" % (nd, nd, p["c_filt"], p["c_filt"]))
    o.append("XCA tapa vrh oa pl vdda vss r1_por_cmp")
    o.append("XCD vdd refd od pl vdda vss r1_por_cmp")
    o.append("XIA oa gooda vdda vss r1_por_inv")
    o.append("XID od goodd vdda vss r1_por_inv")
    o.append("XIDB goodd badd vdda vss r1_por_inv")
    o.append(hvn("XHD1", "refd", "goodd", "vrl", "vss", 1, 0.5))
    o.append(hvn("XHD2", "refd", "badd", "vrh", "vss", 1, 0.5))
    o.append("* rst = NOT (gooda AND goodd): discharges the delay capacitor")
    o.append("XNR gooda goodd rst vdda vss r1_por_nand2")
    o.append("* delay: PMOS stack from pbias charges the MIM; Schmitt; ready = NOT sy")
    nodes = ["vdda"] + ["st_%d" % i for i in range(1, p["n_st"])] + ["cdel"]
    for i, (a, b) in enumerate(zip(nodes[:-1], nodes[1:])):
        o.append(hvp("XST_%d" % i, b, "pl", a, "vdda", 0.5, 4))
    o.append("XCDEL cdel vss cap_cmim w=%gu l=%gu m=1 mm_ok=1" % (p["w_c"], p["w_c"]))
    o.append(hvn("XRST", "cdel", "rst", "vss", "vss", 1, 0.5))
    o.append("XSCH cdel sy vdda vss r1_por_schmitt")
    o.append("XIR sy ready vdda vss r1_por_inv")
    o.append("* down-shift to the 1.2 V domain (revision 1d): thick NMOS pass from VDD gated by ready (VDDA level), rhigh")
    o.append("* pull-down (about 2 MOhm) on por_raw, then two thin inverters. por_raw is defined low whenever ready is low or")
    o.append("* VDDA is absent, so por_n cannot follow a fast VDD ramp (revision 1c inverter pair did: chain c, ff 10 us ramp).")
    o.append(hvn("XDPS", "vdd", "ready", "por_raw", "vss", 1, 0.5))
    o.append("XRPD por_raw vss sub! rhigh w=0.5u l=%gu m=1 b=0 mm_ok=1" % p["l_rpd"])
    o.append("XDP1 o3 por_raw vdd vdd sg13_lv_pmos w=1u l=0.13u ng=1 m=1 mm_ok=1")
    o.append("XDN1 o3 por_raw vss vss sg13_lv_nmos w=0.5u l=0.13u ng=1 m=1 mm_ok=1")
    o.append("XDP2 por_n o3 vdd vdd sg13_lv_pmos w=1u l=0.13u ng=1 m=1 mm_ok=1")
    o.append("XDN2 por_n o3 vss vss sg13_lv_nmos w=0.5u l=0.13u ng=1 m=1 mm_ok=1")
    o.append(".ends r1_por")
    o.append("")
    # ---------------------------------------------------------------- VREF buffer (revision 2, D20)
    o.append("* r1_vbuf (revision 2, decision D20): unity-gain buffer of the raw bandgap vref (gate input only) for the")
    o.append("* r1_safe string, the r1_isense pedestal arms and the r1_t2f vref pin. Two stages: NMOS input pair")
    o.append("* (XM1 gate = vin = raw vref on the mirror-diode side, XM2 gate = vout), PMOS mirror load, high-impedance node x1")
    o.append("* compensated by XCC to vss (dominant pole), NMOS source follower XM7 (drain at vdda: sources the load current),")
    o.append("* NMOS sink XM8. The output device has its drain on the supply, so a vdda step does not move vout through")
    o.append("* a gate-source path (the PMOS common-source version of 2026-10-26 failed the supply step). Bias: the r1_bias")
    o.append("* leg ibvb sources into the NMOS diode XMB (5 units, 1 uA each at tt); tail XMT 2 units (2 uA), sink XM8 4 units of")
    o.append("* twice the width (8 uA). No enable, no trim.")
    o.append(".subckt r1_vbuf vin vout ibn vdda vss")
    o.append(hvn("XM1", "d1", "vin", "ns", "vss", p["w_in"], p["l_in"], int(p["m_in"])))
    o.append(hvn("XM2", "x1", "vout", "ns", "vss", p["w_in"], p["l_in"], int(p["m_in"])))
    o.append(hvp("XM3", "d1", "d1", "vdda", "vdda", p["w_ld"], p["l_ld"]))
    o.append(hvp("XM4", "x1", "d1", "vdda", "vdda", p["w_ld"], p["l_ld"]))
    # single-finger units (m), as drawn: XMB m_b x w_nb, XMT m_t x w_nb, XM8 m_s x w_s (w_s = 2 w_nb: 2 uA per unit), XM7 m_o x w_o
    o.append(hvn("XMB", "ibn", "ibn", "vss", "vss", p["w_nb"], p["l_nb"], int(p["m_b"])))
    o.append(hvn("XMT", "ns", "ibn", "vss", "vss", p["w_nb"], p["l_nb"], int(p["m_t"])))
    o.append(hvn("XM8", "vout", "ibn", "vss", "vss", p["w_s"], p["l_nb"], int(p["m_s"])))
    o.append(hvn("XM7", "vdda", "x1", "vout", "vss", p["w_o"], p["l_o"], int(p["m_o"])))
    for i in range(int(p["n_cc"])):
        o.append("XCC%d x1 vss cap_cmim w=%gu l=%gu m=1 mm_ok=1" % (i + 1, p["s_cc"], p["s_cc"]))
    o.append(".ends r1_vbuf")
    o.append("")
    # ---------------------------------------------------------------- top
    pins = " ".join(l[0] for l in LEGS)
    o.append("* r1_bias top: %d output legs (%d units) + %d internal leg unit(s) + r1_por + r1_vbuf. pbias/pcasc are inputs from r1_bgr (the T2F takes them directly)." %
             (len(LEGS), sum(l[1] for l in LEGS), sum(int(p[k]) for _, k in INT_LEGS)))
    o.append("* Revision 2: input vref (raw r1_bgr output, gate load only), output vref_b (buffered, D20).")
    o.append(".subckt r1_bias vdda vdd vss pbias pcasc %s por_n vref vref_b" % pins)
    for name, m in LEGS:
        o.append("XL_%s %s pbias pcasc vdda r1_bias_leg m=%d" % (name, name, m))
    for name, key in INT_LEGS:
        o.append("XL_%s %s pbias pcasc vdda r1_bias_leg m=%d" % (name, name, int(p[key])))
    o.append("XPOR vdda vdd vss pbias pcasc por_n r1_por")
    o.append("XVB vref vref_b ibvb vdda vss r1_vbuf")
    o.append(".ends r1_bias")
    return "\n".join(o) + "\n"


if __name__ == "__main__":
    out = "r1_bias.spice"
    kv = {}
    for a in sys.argv[1:]:
        if "=" in a:
            k, v = a.split("=", 1)
            kv[k] = type(P[k])(v)
        else:
            out = a
    open(out, "w").write(gen(kv))
    print("wrote", out)
