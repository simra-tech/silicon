#!/usr/bin/env python3
"""Generate the r1_bgr schematic netlist (SPICE subcircuit) from the G1 Sep-19 g1_bgr cell.

Derived from designs/g1-guardian/blocks/g1_bgr/xschem/g1_bgr.spice (Sep-19 compact bandgap).
Changes against G1 (reason: the PDK HBT mismatch is one independent 10 % area draw per
instance, independent of Nx, so only separate unit instances average it):
  * Q1 = N1 unit npn13G2 instances, Q2 = N2 instances (area ratio N2/N1),
  * Q1 branch fed by M unit mirror legs (current ratio M:1), dVBE = Vt ln(M*N2/N1),
  * Q3 (output VBE) = N3 instances, NMOS cascode MNC1 = M units of 20/1,
  * R1, R2 lengths re-sized; RB re-sized,
  * r4 test mode (Q1B, MSW1/2, MNI2, MPI2) removed: not in the R1 interface.
Unit PMOS leg (10/4 um mirror + 10/4 um cascode at about 4.1 uA) and the pbias/pcasc
pins are unchanged, so G1 T2F mirror legs stay compatible.
Every unit is a separate instance so that each draws its own mismatch.
Usage: python3 gen_r1_bgr.py [--n1 12 --n2 48 --n3 4 --m 8 --r1 84 --r2 347.5 --rb 500 --out r1_bgr.spice]
"""
import argparse

def gen(n1, n2, n3, m, r1, r2, rb, rx, name="r1_bgr"):
    L = []
    a = L.append
    a("* r1_bgr generated by gen_r1_bgr.py n1=%d n2=%d n3=%d m=%d r1=%gu r2=%gu rb=%gu rx=%gu" % (n1, n2, n3, m, r1, r2, rb, rx))
    a(".subckt %s vdd vss vref iptat pbias pcasc vbe dvbe" % name)
    P = "sg13_hv_pmos w=10u l=4u ng=1 m=1 mm_ok=1"
    # Q1 branch: M unit legs into n1
    for k in range(m):
        a("XMP1_%d d1_%d pbias vdd vdd %s" % (k, k, P))
        a("XMC1_%d n1 pcasc d1_%d d1_%d %s" % (k, k, k, P))
        a("XMNC1_%d n1 vb2 vbe vss sg13_hv_nmos w=20u l=1u ng=1 m=1 mm_ok=1" % k)
    # Q2 branch (diode side of the mirror)
    a("XMP2 d2 pbias vdd vdd %s" % P)
    a("XMC2 pbias pcasc d2 d2 %s" % P)
    a("XRB pbias pcasc sub! rppd w=1u l=%gu m=1 b=0 mm_ok=1" % rb)
    a("XMNC2 pcasc vb2 c2 vss sg13_hv_nmos w=20u l=1u ng=1 m=1 mm_ok=1")
    # cascode gate bias leg
    a("XMP5 d5 pbias vdd vdd %s" % P)
    a("XMC5 vb2 pcasc d5 d5 %s" % P)
    a("XRX vb2 vd1 sub! rppd w=1u l=%gu m=1 b=0 mm_ok=1" % rx)
    a("XQD1 vd1 vd1 vd2 vss npn13G2 Nx=1 mm_ok=1")
    a("XQD2 vd2 vd2 vss vss npn13G2 Nx=1 mm_ok=1")
    for k in range(n1):
        a("XQ1_%d vbe vbe vss vss npn13G2 Nx=1 mm_ok=1" % k)
    for k in range(n2):
        a("XQ2_%d c2 vbe dvbe vss npn13G2 Nx=1 mm_ok=1" % k)
    a("XR1 dvbe vss sub! rppd w=1u l=%gu m=1 b=0 mm_ok=1" % r1)
    # output leg
    a("XMP3 d3 pbias vdd vdd %s" % P)
    a("XMC3 vref pcasc d3 d3 %s" % P)
    a("XR2 vref vbe3 sub! rppd w=1u l=%gu m=1 b=0 mm_ok=1" % r2)
    for k in range(n3):
        a("XQ3_%d vbe3 vbe3 vss vss npn13G2 Nx=1 mm_ok=1" % k)
    # PTAT current output leg
    a("XMP4 d4 pbias vdd vdd %s" % P)
    a("XMC4 iptat pcasc d4 d4 %s" % P)
    # start-up (unchanged from G1)
    a("XMPS det pbias vdd vdd %s" % P)
    a("XRDET det vss sub! rhigh w=0.5u l=735u m=1 b=0 mm_ok=1")
    a("XMNI kick det vss vss sg13_hv_nmos w=1u l=0.5u ng=1 m=1 mm_ok=1")
    a("XMPI kick det vdd vdd sg13_hv_pmos w=2u l=0.5u ng=1 m=1 mm_ok=1")
    a("XMKFB pbias kick vss vss sg13_hv_nmos w=1u l=4u ng=1 m=1 mm_ok=1")
    a(".ends")
    return "\n".join(L) + "\n"

if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--n1", type=int, default=12); p.add_argument("--n2", type=int, default=48)
    p.add_argument("--n3", type=int, default=4); p.add_argument("--m", type=int, default=8)
    p.add_argument("--r1", type=float, default=84); p.add_argument("--r2", type=float, default=347.5)
    p.add_argument("--rb", type=float, default=500); p.add_argument("--rx", type=float, default=192)
    p.add_argument("--name", default="r1_bgr"); p.add_argument("--out", default="r1_bgr.spice")
    a = p.parse_args()
    open(a.out, "w").write(gen(a.n1, a.n2, a.n3, a.m, a.r1, a.r2, a.rb, a.rx, a.name))
