#!/usr/bin/env python3
"""Generate r1_safe.spice (analog part of r1_safe: window comparators, 6-bit threshold DACs with 6-bit offset
calibration summed into the DAC; revision 3).
Usage: python3 gen_safe.py [KEY=VALUE ...] [--out FILE]   (overrides for sizing studies only).
Revision 2 (6-bit DAC only, 63-unit string, 64:1 muxes, mirror w16 l4) is kept as r1_safe_r2.spice (superseded)."""
import sys, os
S = {
    "WIN": "20", "LIN": "2",      # comparator input pairs (thick PMOS), each device, ng=4
    "ITAIL_M": "8",               # tail units (pu = 5 uA): 40 uA per pair (20 uA per side at balance)
    "RSL": "308", "RSW": "2",     # source degeneration per side: rppd w=RSW l=RSL um (2 x 308 um: about 40 kOhm); rev 2: rhigh w1 l30
    "LG": "2", "WG": "2",         # gain-stage NMOS (10 uA; W/L 1/4 of the mirror at 40 uA: same current density)
    "LM": "10", "WM": "40",       # NMOS mirror load (40 uA per side at balance); rev 2 had w16 l4 (18 mV sigma term)
    "DEG": "rppd",                # degeneration resistor model: rppd (rev 3; 7x lower mismatch per area than rhigh) or rhigh (rev 2)
    "FINE": "4",                  # string units per coarse threshold tap: 63*FINE units, 8-bit fine muxes
    "IH_M": "1",                  # multiplicity of the hysteresis source stack
    "CREF": "0",                  # reference decoupling cmim side (um); 0 = none
    "LH": "8", "WH": "0.5", "NH": "3",  # hysteresis source: NH series thick PMOS w=WH l=LH (about 0.1 uA; one w=1 l=4 device gave 30 mV Vod hysteresis in revision 1)
}
OUT = "r1_safe.spice"
args = sys.argv[1:]
if "--out" in args:
    i = args.index("--out"); OUT = args[i + 1]; del args[i:i + 2]
for a in args:
    k, v = a.split("=", 1); S[k] = v
F = int(S["FINE"]); NU = 63 * F                     # string units (252)
NB = 8 if F == 4 else (6 if F == 1 else sys.exit("FINE must be 1 or 4"))
L = []
w = L.append
w("* GENERATED by gen_safe.py -- do not edit; sizes: " + " ".join("%s=%s" % kv for kv in sorted(S.items())))
w("""* r1_safe analog, revision 3: two window comparators per channel (overcurrent high, negative/phase-short low),
* each with a threshold DAC that sums a 6-bit threshold code and a 6-bit offset-calibration code. IHP SG13G2,
* schematic-level SPICE source.
*
* String: one shared rppd string of 63*F units (F = %(F)d, unit %(RU).0f Ohm, w=2 l=%(UL).3g) from VREF (T%(NU)d) to VSS (T0),
*   fine taps Tn = n/%(NU)d*VREF; coarse threshold taps are every F-th fine tap (same 252 kOhm, 4.2 uA as revision 2).
* Each comparator has two %(MX)d:1 thick-NMOS tree multiplexers: REFP = T(nP), REFN = T(nN), nP/nN are %(NB)d-bit codes
*   (1.2 V logic) from the summing logic in r1_safe (digital, see README): with cell threshold code c (0..63) and
*   calibration code k (0..63, d = k - 32):
*     nP = F*c + ceil(d/2),  nN = F*(63 - c) - floor(d/2),   both clipped to 0..%(NU)d
*     Vth_cell = REFP - REFN = VREF*(2*F*c - %(NU)d + d)/%(NU)d = (2c-63)/63*VREF + d*VREF/%(NU)d
*   i.e. the threshold LSB is 2*VREF/63 = 33.3 mV Vod and the calibration step is VREF/%(NU)d = LSB/%(STEPS)d (4.17 mV Vod),
*   range -32..+31 steps (-4.0..+3.9 LSB). Overcurrent cell: c = thr_oc, INP=OUTP, INN=OUTN.
*   Negative cell: c = 63 - thr_neg, INP=OUTN, INN=OUTP (trips when Vod < (2*thr_neg-63)/63*VREF - d*VREF/%(NU)d).
* With r1_isense (Vod = 14*(Vsh - VREF/26)) the shunt-referred threshold is Vsh_th = VREF*(1/26 + (2*code-63)/882).
* Comparator r1_safe_cmp: trips (OUT high) when (INP - INN) > (REFP - REFN).
*   Inputs are thick-oxide PMOS gates (rated 3.3 V); no divider. The sense outputs are <= VDD by construction.
*   Continuous time, no clock (no clock-edge race as in G1 TRIP F1). Hysteresis by an output-switched current.
*   Output: 1.2 V logic (thick-input inverter on VDD, then a thin-oxide inverter), high = threshold crossed.
* Device conventions: PMOS bulks to VDDA except input pairs (bulk = own tail); NMOS bulks to VSS; mm_ok=1.
""" % {"F": F, "NU": NU, "MX": 2 ** NB, "NB": NB, "UL": 30.8 / F, "RU": 4000.0 / F, "STEPS": 2 * F})
w("""
.subckt r1_safe_ls in vdd vdda vss out outb
XMIP inb in vdd vdd sg13_lv_pmos w=1u l=0.13u ng=1 m=1 mm_ok=1
XMIN inb in vss vss sg13_lv_nmos w=0.5u l=0.13u ng=1 m=1 mm_ok=1
XMN1 a in vss vss sg13_hv_nmos w=4u l=0.45u ng=1 m=1 mm_ok=1
XMN2 b inb vss vss sg13_hv_nmos w=4u l=0.45u ng=1 m=1 mm_ok=1
XMP1 a b vdda vdda sg13_hv_pmos w=0.6u l=0.5u ng=1 m=1 mm_ok=1
XMP2 b a vdda vdda sg13_hv_pmos w=0.6u l=0.5u ng=1 m=1 mm_ok=1
XMB1P outb b vdda vdda sg13_hv_pmos w=2u l=0.5u ng=1 m=1 mm_ok=1
XMB1N outb b vss vss sg13_hv_nmos w=1u l=0.45u ng=1 m=1 mm_ok=1
XMB2P out outb vdda vdda sg13_hv_pmos w=2u l=0.5u ng=1 m=1 mm_ok=1
XMB2N out outb vss vss sg13_hv_nmos w=1u l=0.45u ng=1 m=1 mm_ok=1
.ends r1_safe_ls
""")
# 2^NB:1 tree mux over the fine taps (taps above NU are tied to T(NU) at the instance)
NT = 2 ** NB
taps = " ".join("t%d" % k for k in range(NU + 1))
mtaps = " ".join("t%d" % k for k in range(NT))
w(".subckt r1_safe_mux %s %s out vss" % (mtaps, " ".join("b%d" % i for i in range(NB)) + " " + " ".join("bb%d" % i for i in range(NB))))
w("* out = t(code), code = sum b_i 2^i; thick NMOS pass switches (gates 0 / 3.3 V), w=0.5 l=0.45")
prev = ["t%d" % k for k in range(NT)]
for lev in range(NB):
    nxt = []
    for k in range(len(prev) // 2):
        n = "out" if lev == NB - 1 else "n%d_%d" % (lev, k)
        w("XS%d_%d_0 %s bb%d %s vss sg13_hv_nmos w=0.5u l=0.45u ng=1 m=1 mm_ok=1" % (lev, k, prev[2 * k], lev, n))
        w("XS%d_%d_1 %s b%d %s vss sg13_hv_nmos w=0.5u l=0.45u ng=1 m=1 mm_ok=1" % (lev, k, prev[2 * k + 1], lev, n))
        nxt.append(n)
    prev = nxt
w(".ends r1_safe_mux\n")
# string
w(".subckt r1_safe_string vref %s vss" % taps)
w("* %d rppd units of %.0f Ohm between VREF (T%d) and VSS (T0); 4.2 uA at 1.05 V" % (NU, 4000.0 / F, NU))
for k in range(NU):
    w("XRS%d t%d t%d vss rppd w=2u l=%.4gu m=1 b=0 mm_ok=1" % (k, k + 1, k, 30.8 / F))
w("Rt%d t%d vref 1e-3" % (NU, NU))
w("Rt0 t0 vss 1e-3")
w(".ends r1_safe_string\n")
# comparator
_n = int(S["NH"]); _nodes = ["vdda"] + ["hn%d" % i for i in range(1, _n)] + ["hs"]
hstack = "".join("XMH1%s %s vbp %s vdda sg13_hv_pmos w=%su l=%su ng=1 m=%s mm_ok=1\n" % (chr(97 + i), _nodes[i + 1], _nodes[i], S["WH"], S["LH"], S["IH_M"]) for i in range(_n))
w(""".subckt r1_safe_cmp inp inn refp refn out ibias vdda vdd vss
* ibias: 5 uA sunk into the pin (from r1_bgr PTAT branch; ideal source in this step)
XMBN ibias ibias vss vss sg13_hv_nmos w=4u l=1u ng=1 m=1 mm_ok=1
XMB2 vbp ibias vss vss sg13_hv_nmos w=4u l=1u ng=1 m=1 mm_ok=1
XMBP vbp vbp vdda vdda sg13_hv_pmos w=4u l=2u ng=1 m=1 mm_ok=1
* input pairs, 40 uA tails each
XMTA ta vbp vdda vdda sg13_hv_pmos w=4u l=2u ng=1 m=@ITM@ mm_ok=1
XMTB tb vbp vdda vdda sg13_hv_pmos w=4u l=2u ng=1 m=@ITM@ mm_ok=1
* each pair is source-degenerated (rhigh per side) so that it stays linear over the full +-1.05 V input range:
* without degeneration both pairs saturate for |Vth| > about 0.1 V and the comparison fails (run safe-cmp-20261020-r1).
XMA1 d1 inp sa1 ta sg13_hv_pmos w=@WIN@u l=@LIN@u ng=4 m=1 mm_ok=1
XMA2 d2 inn sa2 ta sg13_hv_pmos w=@WIN@u l=@LIN@u ng=4 m=1 mm_ok=1
XRA1 ta sa1 vss @DEG@ w=@RSW@u l=@RSL@u m=1 b=0 mm_ok=1
XRA2 ta sa2 vss @DEG@ w=@RSW@u l=@RSL@u m=1 b=0 mm_ok=1
XMB1 d1 refn sb1 tb sg13_hv_pmos w=@WIN@u l=@LIN@u ng=4 m=1 mm_ok=1
XMB2I d2 refp sb2 tb sg13_hv_pmos w=@WIN@u l=@LIN@u ng=4 m=1 mm_ok=1
XRB1 tb sb1 vss @DEG@ w=@RSW@u l=@RSL@u m=1 b=0 mm_ok=1
XRB2 tb sb2 vss @DEG@ w=@RSW@u l=@RSL@u m=1 b=0 mm_ok=1
* NMOS mirror load: d1 diode, d2 output (d2 rises when (inp-inn) > (refp-refn))
XML1 d1 d1 vss vss sg13_hv_nmos w=@WM@u l=@LM@u ng=1 m=1 mm_ok=1
XML2 d2 d1 vss vss sg13_hv_nmos w=@WM@u l=@LM@u ng=1 m=1 mm_ok=1
* gain stage: NMOS common source, PMOS source 10 uA
XMG o1 d2 vss vss sg13_hv_nmos w=@WG@u l=@LG@u ng=1 m=1 mm_ok=1
XMGL o1 vbp vdda vdda sg13_hv_pmos w=4u l=2u ng=1 m=2 mm_ok=1
* inverter (3.3 V): o2 high when tripped
XMI1P o2 o1 vdda vdda sg13_hv_pmos w=2u l=0.5u ng=1 m=1 mm_ok=1
XMI1N o2 o1 vss vss sg13_hv_nmos w=1u l=0.45u ng=1 m=1 mm_ok=1
* hysteresis: a small current steered into d2 while tripped (o1 low) and into d1 otherwise (o2 low);
* steering (not switching off) keeps node hs driven at all times
@HSTACK@XMH2 d2 o1 hs vdda sg13_hv_pmos w=1u l=0.5u ng=1 m=1 mm_ok=1
XMH3 d1 o2 hs vdda sg13_hv_pmos w=1u l=0.5u ng=1 m=1 mm_ok=1
* down-shift to 1.2 V: thick-input inverter on VDD, then thin inverter
XMD1P o3 o2 vdd vdd sg13_hv_pmos w=2u l=0.5u ng=1 m=1 mm_ok=1
XMD1N o3 o2 vss vss sg13_hv_nmos w=1u l=0.45u ng=1 m=1 mm_ok=1
XMD2P out o3 vdd vdd sg13_lv_pmos w=1u l=0.13u ng=1 m=1 mm_ok=1
XMD2N out o3 vss vss sg13_lv_nmos w=0.5u l=0.13u ng=1 m=1 mm_ok=1
.ends r1_safe_cmp
""".replace("@WIN@", S["WIN"]).replace("@LIN@", S["LIN"]).replace("@ITM@", S["ITAIL_M"]).replace("@IHM@", S["IH_M"]).replace("@LH@", S["LH"]).replace("@RSL@", S["RSL"]).replace("@RSW@", S["RSW"]).replace("@HSTACK@", hstack).replace("@LG@", S["LG"]).replace("@WG@", S["WG"]).replace("@LM@", S["LM"]).replace("@WM@", S["WM"]).replace("@DEG@", S["DEG"]))
# comparator with its two DAC muxes and level shifters
pb = lambda p: " ".join("%s%d" % (p, i) for i in range(NB))
mt = " ".join("t%d" % min(k, NU) for k in range(NT))
w(".subckt r1_safe_thr inp inn %s %s %s out ibias vdda vdd vss" % (taps, pb("p"), pb("n")))
w("* one comparator + its threshold DAC: REFP = T(nP), REFN = T(nN); p*/n* = 1.2 V code bits (summed codes)")
for i in range(NB):
    w("XLSP%d p%d vdd vdda vss bp%d bbp%d r1_safe_ls" % (i, i, i, i))
    w("XLSN%d n%d vdd vdda vss bn%d bbn%d r1_safe_ls" % (i, i, i, i))
w("XMXP %s %s %s refp vss r1_safe_mux" % (mt, pb("bp"), pb("bbp")))
w("XMXN %s %s %s refn vss r1_safe_mux" % (mt, pb("bn"), pb("bbn")))
if float(S["CREF"]) > 0:
    w("* reference decoupling: cmim on each mux output (filters comparator kickback into the shared string)")
    w("XCRP refp vss cap_cmim w=%su l=%su m=1 mm_ok=1" % (S["CREF"], S["CREF"]))
    w("XCRN refn vss cap_cmim w=%su l=%su m=1 mm_ok=1" % (S["CREF"], S["CREF"]))
w("XCMP inp inn refp refn out ibias vdda vdd vss r1_safe_cmp")
w(".ends r1_safe_thr\n")
# top: four comparators; code ports are the summed nP/nN codes of each comparator (cell frame, see header)
cmps = ("oa", "na", "ob", "nb")
ports = " ".join(pb("%s_p" % c) + " " + pb("%s_n" % c) for c in cmps)
w(".subckt r1_safe_an outa_p outa_n outb_p outb_n vref %s oc_a neg_a oc_b neg_b ibias_oa ibias_na ibias_ob ibias_nb vdda vdd vss" % ports)
w("* oc_x high: Vod_x > Vth(thr_oc_x) (+ cal);  neg_x high: Vod_x < Vth(thr_neg_x) (- cal).  <c>_p*/<c>_n*: nP/nN, bit 0 = LSB.")
w("XSTR vref %s vss r1_safe_string" % taps)
for ch in ("a", "b"):
    w("XOC%s out%s_p out%s_n %s %s %s oc_%s ibias_o%s vdda vdd vss r1_safe_thr" % (ch, ch, ch, taps, pb("o%s_p" % ch), pb("o%s_n" % ch), ch, ch))
    w("XNG%s out%s_n out%s_p %s %s %s neg_%s ibias_n%s vdda vdd vss r1_safe_thr" % (ch, ch, ch, taps, pb("n%s_p" % ch), pb("n%s_n" % ch), ch, ch))
w(".ends r1_safe_an")
here = os.path.dirname(os.path.abspath(__file__))
p = OUT if os.path.isabs(OUT) else os.path.join(here, OUT)
open(p, "w").write("\n".join(L) + "\n")
print(p)
