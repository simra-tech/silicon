#!/usr/bin/env python3
"""Write r1_gate_<variant>_lvs.cdl for the KLayout LVS from the R1 netlist of record.

Inputs (both in ../schematic): g1_cells_copy.spice (byte copy of the G1 cell netlist) and r1_gate.spice (top cells
r1_gate_hv and r1_gate_lv). The CDL holds the G1 cell subcircuits the variant uses plus the variant's top subcircuit.
The primitive rewrite is the G1 one (spice2cdl.py, copied unchanged): X<name> -> M<name>, ng and mm_ok dropped.
The G1 top subcircuit g1_gate of the cell file is not used. Usage: python3 make_lvs_cdl.py [hv|lv ...]
"""
import os, re, sys
from spice2cdl import convert
HERE = os.path.dirname(os.path.abspath(__file__))
SCH = os.path.join(HERE, '..', 'schematic')
NEED = {'hv': ['g1_lv_inv', 'g1_lvlup', 'g1_hv_nor2', 'g1_hv_inv', 'g1_lvldn'], 'lv': ['g1_lv_nand2', 'g1_lv_inv']}


def subckts(path):
    d, cur, name = {}, None, None
    for line in open(path):
        t = line.split()
        if t and t[0] == '.subckt':
            name, cur = t[1], [line.rstrip('\n')]
        elif t and t[0] == '.ends' and cur is not None:
            cur.append(line.rstrip('\n')); d[name] = cur; cur = None
        elif cur is not None:
            cur.append(line.rstrip('\n'))
    return d


cells = subckts(os.path.join(SCH, 'g1_cells_copy.spice'))
tops = subckts(os.path.join(SCH, 'r1_gate.spice'))
for v in (sys.argv[1:] or ['hv', 'lv']):
    lines = []
    for c in NEED[v]:
        lines += cells[c]
    lines += tops['r1_gate_' + v]
    out = convert(lines, 'vss')
    p = os.path.join(HERE, 'r1_gate_%s_lvs.cdl' % v)
    open(p, 'w').write('* CDL for KLayout LVS, generated by layout/make_lvs_cdl.py from schematic/r1_gate.spice and schematic/g1_cells_copy.spice (substrate net = vss)\n'
                       + '\n'.join(out) + '\n')
    print('wrote', p, len(out), 'lines')
