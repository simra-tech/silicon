#!/usr/bin/env python3
"""Generate schematic/r1_adc_r4p.spice: revision-4 MSB pre-switch option (decision 0 at a low common mode).

Finding (run r4-sweep-ss125): at ss / 125 C / 1.08 V decision 0, which sees the input common mode 0.6 V, does not
resolve within the tick for |Vin| up to about 40 mV; an unresolved decision reads as 1 (comparator outputs reset
high), so negative inputs between about -40 and -7 mV are outside the 30 LSB redundancy (errors up to 70 LSB).
Pre-switch: while slice X waits for decision 0 (winX = 1 and decision-0 flag not yet set) the bottom plates of
BOTH C12 (P and N, 16 Cu each) go VREF -> GND. The differential top-plate voltage is unchanged; the top-plate common
mode drops by about VREF * 16 Cu / C_side (to about 0.1 V), where the comparator decides in time. At the decision-0
strobe the C12 of the losing side returns to VREF (b0 = 1: N side back; b0 = 0: P side back), which is the same
differential state as the normal algorithm (one C12 at GND). Decisions 1..13 are unchanged.
Logic (XSPICE, behavioural like the rest of the SAR): preX = winX AND NOT fvX0; cpX12 = fpX0 OR preX;
cnX12 = fnX0 OR preX. Cells r1_sar4p_logic, r1_adc4p_core_fast, r1_adc4p_core; they use r1_adc_r4.spice cells
(include both files). r1_adc_r4.spice is not changed (frozen for the revision-4 campaign).
Python 3.6 compatible.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen_r1_adc_r4 as r4

NB, ND = r4.NB, r4.ND


def sar_logic_pre():
    t = r4.sar_logic().replace("r1_sar4_logic", "r1_sar4p_logic")
    add = []
    for ch in ("a", "b"):
        add += ["APRE%s [d_win%s nfv%s0] pre%s r1_and" % (ch, ch, ch, ch),
                "AOP%s [fp%s0 pre%s] fpx%s0 r1_or" % (ch, ch, ch, ch),
                "AON%s [fn%s0 pre%s] fnx%s0 r1_or" % (ch, ch, ch, ch)]
    # bridge the pre-switched decision-0 controls instead of fpX0 / fnX0
    i = t.index("ADB [")
    j = t.index("]", i)
    head = t[i:j]
    for ch in ("a", "b"):
        head = head.replace(" fp%s0 fn%s0 " % (ch, ch), " fpx%s0 fnx%s0 " % (ch, ch))
    assert head.count("fpx") == 2 and head.count("fnx") == 2, head[:200]
    t = t[:i] + "\n".join(add) + "\n" + head + t[j:]
    t = t.replace("* r1_sar4_logic: XSPICE SAR registers", "* r1_sar4p_logic (MSB pre-switch, gen_r1_adc_r4p.py): XSPICE SAR registers")
    return t


def core_pre(kind):
    t = r4.core(kind)
    old = {"fast": "r1_adc4_core_fast", "full": "r1_adc4_core"}[kind]
    new = {"fast": "r1_adc4p_core_fast", "full": "r1_adc4p_core"}[kind]
    t = t.replace(".subckt %s " % old, ".subckt %s " % new).replace(".ends %s" % old, ".ends %s" % new)
    t = t.replace(" r1_sar4_logic\n", " r1_sar4p_logic\n")
    t = t.replace("* %s: R1 ADC revision-4 core." % old, "* %s: R1 ADC revision-4 core with the MSB pre-switch (r1_sar4p_logic)." % new)
    return t


def main():
    hdr = ("* r1_adc_r4p.spice -- R1 ADC revision 4, MSB pre-switch option (generated by gen_r1_adc_r4p.py; do not edit)\n"
           "* Include after r1_adc_r4.spice (uses its cells).\n")
    with open(os.path.join(HERE, "r1_adc_r4p.spice"), "w") as f:
        f.write(hdr + sar_logic_pre() + core_pre("fast") + core_pre("full"))
    print("wrote r1_adc_r4p.spice")


if __name__ == "__main__":
    main()
