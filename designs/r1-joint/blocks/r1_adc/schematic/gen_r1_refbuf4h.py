#!/usr/bin/env python3
"""Generate schematic/r1_refbuf4h.spice: r1_refbuf4 with a high-impedance input (revision-4 finding, 2026-10-21).

Finding (run r4-refn-tt-cf0b): r1_refbuf4 takes vbg through a 23-segment rhigh divider (about 344 kohm to ground)
and regulates vref to the 22/23 tap. The r1_bgr vref output is unbuffered (90-200 kohm source, r1_bgr README), so the
divider pulls vbg from 1.045 V to 0.673 V (190 kohm) and vref to 0.652 V. r1_refbuf4h removes the divider: the
error-amplifier input gate is vbg itself (no DC current), and vref = vbg (about 1.045 V instead of 1.0 V; the ADC
full scale scales with vref, +4.5 %). Optional input filter: Cf from vbg to ground (cf, MIM, 0 = none) forms a
low-pass with the bandgap source resistance. Everything else is r1_refbuf4 (chosen R2-4 option).
r1_adc_r4.spice is not changed (frozen for the revision-4 campaign). Python 3.6 compatible.
"""
import os
import re
import sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)


def main():
    s = open(os.path.join(HERE, "r1_adc_r4.spice")).read()
    i = s.index(".subckt r1_refbuf4 ")
    j = s.index(".ends r1_refbuf4", i) + len(".ends r1_refbuf4")
    t = s[i:j]
    t = "\n".join(l for l in t.split("\n") if not l.startswith("XRD"))
    t = t.replace(".subckt r1_refbuf4 vbg vref vdda gnd ", ".subckt r1_refbuf4h vbg vref vdda gnd cfw=0 ")
    t = t.replace(".ends r1_refbuf4", ".ends r1_refbuf4h")
    t = t.replace("XM1  na  vtap ntl", "XM1  na  vbg ntl")
    assert "vtap" not in t, t
    # input filter: cfw = side of a square MIM (0: none). cap_cmim needs w > 0, so the filter is a separate cell.
    hdr = ("* r1_refbuf4h.spice -- r1_refbuf4 with a high-impedance input (generated by gen_r1_refbuf4h.py; do not edit)\n"
           "* Include after r1_adc_r4.spice. Input filter: instantiate r1_reffilt4 (Cf = MIM w x w) on vbg.\n")
    filt = (".subckt r1_reffilt4 vbg gnd w=58u\n"
            "XCF vbg gnd cap_cmim w={w} l={w} m=1\n"
            ".ends r1_reffilt4\n")
    open(os.path.join(HERE, "r1_refbuf4h.spice"), "w").write(hdr + t.replace(" cfw=0", "") + "\n" + filt)
    print("wrote r1_refbuf4h.spice")


if __name__ == "__main__":
    main()
