#!/usr/bin/env python3
"""Generate the R1 ADC revision-6 schematic-level SPICE library schematic/r1_adc_r6.spice (PLAN.md D28, track T2o,
2026-10-28). Revision 5 (r1_adc_r5.spice, gen_r1_adc_r5.py) stays unchanged; revision 6 = the whole revision-5 library
(copied verbatim, same cell names) plus the revision-6 cells below. Do not include r1_adc_r5.spice and r1_adc_r6.spice
in the same deck (same cell names).

Revision 6 against revision 5:
  * r1_cmp6_clkgen (D28 item 1, strobe retiming): the r1_cmp4_clkgen devices with the input of the five-inverter delay
    chain on gnd instead of clk30. The chain output x is then constantly high and mclk = NAND(clk30, x) = NOT clk30:
    the comparator reset starts at the rising clk30 edge through the same NAND gate as before (same delay, same SAR
    hold timing), and the comparator evaluates from the falling clk30 edge (16.67 ns after the rising edge at 50 % duty,
    r1_osc 48.6-51.3 %) to the next rising edge, where the SAR takes the decision. No other device changes; the chain
    devices are kept so that the layout change is one gate connection.
  * r1_refbuf6 (D28 item 2, reference path): r1_refbuf5 with the LSB-array follower and its sink three times wider
    (msfl 8 -> 24, mibl 40 -> 120): the same current density, three times the current (vrefl branch 200 -> 600 uA at
    the 5 uA bias, +400 uA from VDDA) and about a third of the output impedance (B7 extraction: vrefl follower 298 Ohm
    at tt, 389 Ohm at ss; the time constant at the slice port is set by it, README "Revision 6 and layout B9").
    Pins, the main follower, the error amplifier, the decoupling (ndec 4, ndecl 2 in the layout) and the 10 pF input
    filter r1_reffilt5 (on vbg, the buffer input) are unchanged.
  * Cores r1_adc6_core, r1_adc6_core_fast, r1_adc6_core_fast_mc: the revision-5 cores with r1_cmp6_clkgen.
Python 3.6 compatible.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
R5 = os.path.join(HERE, "r1_adc_r5.spice")
OUT = os.path.join(HERE, "r1_adc_r6.spice")
REFL6 = dict(msfl=24, mibl=120)


def main():
    src = open(R5).read()
    lines = src.split("\n")
    assert lines[0].startswith("* r1_adc_r5.spice"), lines[0]
    body = "\n".join(lines[1:])
    hdr = ("* r1_adc_r6.spice -- R1 12-bit SAR ADC revision 6, schematic-level library (generated by gen_r1_adc_r6.py; do not edit)\n"
           "* Revision 6 (PLAN.md D28): the revision-5 library below, unchanged, plus r1_cmp6_clkgen (comparator strobe from the\n"
           "* falling clk30 edge), r1_refbuf6 (LSB-array follower x3) and the cores r1_adc6_core(_fast, _fast_mc). The revision-5\n"
           "* text follows from its second line on.\n")
    m = re.search(r"^\.subckt r1_cmp4_clkgen .*?^\.ends r1_cmp4_clkgen", src, re.M | re.S).group(0)
    ck = m.replace(".subckt r1_cmp4_clkgen ", ".subckt r1_cmp6_clkgen ").replace(".ends r1_cmp4_clkgen", ".ends r1_cmp6_clkgen")
    old0 = "XPD0 d0 clk30 vdd vdd sg13_lv_pmos"
    old1 = "XND0 d0 clk30 gnd gnd sg13_lv_nmos"
    assert ck.count(old0) == 1 and ck.count(old1) == 1
    ck = ck.replace(old0, "XPD0 d0 gnd vdd vdd sg13_lv_pmos").replace(old1, "XND0 d0 gnd gnd gnd sg13_lv_nmos")
    rb = re.search(r"^\.subckt r1_refbuf5 .*?^\.ends r1_refbuf5", src, re.M | re.S).group(0)
    rb6 = rb.replace(".subckt r1_refbuf5 ", ".subckt r1_refbuf6 ").replace(".ends r1_refbuf5", ".ends r1_refbuf6")
    rb6 = rb6.replace("msfl=8 mibl=40", "msfl=%d mibl=%d" % (REFL6["msfl"], REFL6["mibl"]))
    assert "msfl=%d mibl=%d" % (REFL6["msfl"], REFL6["mibl"]) in rb6
    cores = []
    for c in ("r1_adc5_core", "r1_adc5_core_fast", "r1_adc5_core_fast_mc"):
        cc = re.search(r"^\.subckt %s .*?^\.ends %s$" % (c, c), src, re.M | re.S).group(0)
        n6 = c.replace("r1_adc5_", "r1_adc6_")
        cc = cc.replace(".subckt %s " % c, ".subckt %s " % n6).replace(".ends %s" % c, ".ends %s" % n6)
        assert cc.count(" r1_cmp4_clkgen\n") == 1
        cores.append(cc.replace(" r1_cmp4_clkgen\n", " r1_cmp6_clkgen\n"))
    add = ["",
           "* =============================================================================================",
           "* Revision 6 cells (PLAN.md D28, T2o 2026-10-28)",
           "* =============================================================================================",
           "* r1_cmp6_clkgen: r1_cmp4_clkgen with the delay-chain input on gnd (x = 1): mclk = NOT clk30. Reset (mclk = 0)",
           "* from the rising clk30 edge to the falling edge, evaluate from the falling edge to the next rising edge.",
           ck, "",
           "* r1_refbuf6: r1_refbuf5 with msfl %d / mibl %d (LSB-array follower and sink x3, same density; vrefl branch"
           % (REFL6["msfl"], REFL6["mibl"]),
           "* 600 uA at 5 uA bias). Same pins as r1_refbuf5. Layout: ndec 4, ndecl 2 as for r1_refbuf5.",
           rb6, "",
           "* r1_adc6_core*: the revision-5 cores with r1_cmp6_clkgen (falling-edge strobe).",
           "\n\n".join(cores), ""]
    open(OUT, "w").write(hdr + body.rstrip("\n") + "\n" + "\n".join(add) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
