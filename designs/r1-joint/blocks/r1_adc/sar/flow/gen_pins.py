#!/usr/bin/env python3
"""Pin template of r1_adc_sar (T2j, D21). Writes pins.cfg (LibreLane IO_PIN_ORDER_CFG) and pins.json / pins.md.

usage: gen_pins.py <W> <H> [outdir]
North edge (r1_ctrl side): the x positions of the r1_adc north-edge pins of layouts A-B3
(r1_top/reports/integration_checklist_f.md), snapped to the Metal2 slot grid; new pin cur_trk at x 17.08 (between
adc_start 9.88 and adc_sel 24.28). South edge (slices): the x of the slice pin each net connects to in layout B3
(flow/slice_pin_targets.json, from reports/b3_sar_labels.txt), sorted by x, one slot at least after the previous pin.
Exact slots: same method as r1_ctrl/flow/librelane/gen_pins_v06.py (pins + `$n` gaps = slots - 1 on each side).
Slot grid: Metal2 tracks x = 0.48 + 0.48 i (checked in the final DEF by check_pins.py); slot = every 2nd track.
SPDX-License-Identifier: Apache-2.0"""
import json, math, os, sys

W = float(sys.argv[1]); H = float(sys.argv[2])
OUT = sys.argv[3] if len(sys.argv) > 3 else os.path.dirname(os.path.abspath(__file__))
HERE = os.path.dirname(os.path.abspath(__file__))
STEP = 0.96
nt = int(math.floor((W - 0.48) / 0.48 + 1e-9)) + 1
slots = [0.48 + 0.48 * i for i in range(nt)][::2]


def near(v, after):
    k = min(range(len(slots)), key=lambda i: abs(slots[i] - v))
    return max(k, after + 1)


north = [("adc_hold", 2.0), ("is_smp", 4.0), ("clk", 6.0), ("adc_start", 9.88), ("cur_trk", 17.08), ("adc_sel", 24.28),
         ("adc_valid_a", 38.68)] + [("adc_raw_a[%d]" % k, 53.08 + 14.4 * k) for k in range(14)] + \
        [("adc_valid_b", 254.68)] + [("adc_raw_b[%d]" % k, 269.08 + 14.4 * k) for k in range(12)] + \
        [("adc_raw_b[12]", 431.0), ("adc_raw_b[13]", 433.0), ("por_n", 437.0)]
tg = json.load(open(os.path.join(HERE, "slice_pin_targets.json")))
bus = {"cpa": "cpa[%s]", "cna": "cna[%s]", "cpb": "cpb[%s]", "cnb": "cnb[%s]"}


def vname(n):
    for p, f in bus.items():
        if n.startswith(p) and n[3:].isdigit():
            return f % n[3:]
    return n


south = sorted(((vname(n), xy[0]) for n, xy in tg.items()), key=lambda p: (p[1], p[0]))
pins = []
for side, lst in (("N", north), ("S", south)):
    k = -1
    for n, x in lst:
        k = near(x, k)
        pins.append({"net": n, "edge": side, "k": k, "want_x": round(x, 3), "x": round(slots[k], 3),
                     "y": H if side == "N" else 0.0,
                     "target": ("r1_adc north pin (layouts A-B3)" if side == "N" else
                                "slice pin sar_%s at (%.2f, %.2f) in layout B3" % (n.replace("[", "").replace("]", ""),
                                                                                    *tg[[t for t in tg if vname(t) == n][0]]))})
assert max(p["k"] for p in pins) < len(slots) - 1, "pins do not fit"
cfg = []
for side in "NS":
    sp = sorted([p for p in pins if p["edge"] == side], key=lambda p: p["k"])
    cfg += ["#" + side, "@min_distance=%g" % STEP]
    pos = 0
    for p in sp:
        if p["k"] - pos > 0:
            cfg.append("$%d" % (p["k"] - pos))
        cfg.append(p["net"].replace("[", "\\[").replace("]", "\\]"))
        pos = p["k"] + 1
    rest = len(slots) - 1 - pos
    if rest > 0:
        cfg.append("$%d" % rest)
open(os.path.join(OUT, "pins.cfg"), "w").write("\n".join(cfg) + "\n")
json.dump({"die_um": [W, H], "slot_step_um": STEP, "pins": pins}, open(os.path.join(OUT, "pins.json"), "w"), indent=1)
md = ["# r1_adc_sar pins (generated by flow/gen_pins.py for a %g x %g um die; do not edit)" % (W, H), "",
      "Local frame: macro lower-left corner at the origin, R0. Pins on Metal2 (vertical), %g um slots." % STEP, "",
      "| Pin | Edge | x (um) | wanted x (um) | Connects to |", "| --- | --- | --- | --- | --- |"]
for p in sorted(pins, key=lambda p: (p["edge"], p["x"])):
    md.append("| `%s` | %s | %.2f | %.2f | %s |" % (p["net"], p["edge"], p["x"], p["want_x"], p["target"]))
open(os.path.join(OUT, "pins.md"), "w").write("\n".join(md) + "\n")
print("N %d S %d slots %d max shift %.2f um" % (len(north), len(south), len(slots),
                                                max(abs(p["x"] - p["want_x"]) for p in pins)))
