#!/usr/bin/env python3
"""T2j: extract the SAR input vectors from a behavioural full-core run (sar/sim/tb_beh_*.cir) and write
  sar/tb/vec/<case>.json        frame schedule, clock period, forced decisions, digitised edges
  sar/tb/vec/<case>_stim.vh     Verilog stimulus for tb_sar_vec.v (mclk and comparator outputs, absolute times)
  sar/tb/vec/<case>_sched.vh    frame schedule for the ctrl protocol model in tb_sar_vec.v
  sar/sim/vec/<case>_pwl.inc    PWL sources for the SAR-only behavioural deck sar/sim/tb_beh_sar.cir
Digitisation: threshold 0.6 V, as the adc_bridge of r1_sar5_logic (in_low = in_high = 0.6 V).
Strobe hold: for every decision edge E = ts + (k + 1) T and the comparator used there (o?np for k = 0, o?p for
k >= 1) the output is held at its value at E - 0.6 ns (the behavioural strobe) until E + 1.0 ns. In the deck the
behavioural model resets the decision-0 comparator at its strobe (clkna falls with fv0, 0.5 ns before E), so its
output moves before E; with r1_adc_sar the comparator is reset only from E (mclk), so that edge does not exist.
The r1_cmp4 outputs rise 0.23-0.28 ns after E: the reset response to the behavioural clka (30 ps gate). With the
macro the response comes after its own clka output (mclk -> clka pin delay + response), so the vectors hold the
decision until E + 1.0 ns; the true margin (latch close before the response) is an STA number (README).
Forced "no output" decision (metastable comparator): the comparator output is replaced in
[E(k+1) - 3 ns, E(k+1) + 1.0 ns] by 0.5 V in the PWL (below the 0.6 V threshold) and by 0 in the Verilog stimulus.

usage: vec_extract.py <run id> <case> <frames e.g. ecee> [--force frame,slice,k ...]
"""
import argparse, json, os, sys
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
SAR = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(os.path.dirname(SAR), "sim"))
import rawread  # noqa: E402

T = 1.0 / 30e6
F = 22 * T
T0 = 18 * T
TH = 0.6
ap = argparse.ArgumentParser()
ap.add_argument("run")
ap.add_argument("case")
ap.add_argument("frames")
ap.add_argument("--force", action="append", default=[])
a = ap.parse_args()
raw = os.path.join(os.environ["G1_RESULTS_ROOT"], "r1_adc_sar", a.run, "sar.raw")
sig = {"mclk": "v(xadc.mclk)", "oap": "v(xadc.oap)", "oanp": "v(xadc.oanp)", "obp": "v(xadc.obp)", "obnp": "v(xadc.obnp)",
       "oan": "v(xadc.oan)", "oann": "v(xadc.oann)", "obn": "v(xadc.obn)", "obnn": "v(xadc.obnn)"}
d, var = rawread.read(raw, ["time"] + list(sig.values()))
t = np.abs(d["time"])
tend = float(t[-1])


def edges(y):
    b = y > TH
    ev = [(0.0, int(b[0]))]
    idx = np.nonzero(b[1:] != b[:-1])[0]
    for i in idx:
        t1, t2, y1, y2 = t[i], t[i + 1], y[i], y[i + 1]
        tc = t1 + (TH - y1) * (t2 - t1) / (y2 - y1) if y2 != y1 else t2
        ev.append((float(tc), int(b[i + 1])))
    return ev


def level_at(ev, tq):
    v = ev[0][1]
    for te, x in ev:
        if te <= tq:
            v = x
        else:
            break
    return v


ev = {k: edges(d[v]) for k, v in sig.items()}
nfr = len(a.frames)
ts = [T0 + f * F for f in range(nfr)]
held = []
for f in range(nfr):
    for k in range(14):
        te = ts[f] + (k + 1) * T
        for sl in "ab":
            name = ("o%snp" if k == 0 else "o%sp") % sl
            e = ev[name]
            lo, hi = te - 0.6e-9, te + 1.0e-9
            inside = [x for x in e if lo < x[0] <= hi]
            if inside:
                v0 = level_at(e, lo)
                ev[name] = [x for x in e if not (lo < x[0] <= hi)]
                ev[name] = sorted(ev[name] + [(hi + 1e-13, level_at(e, hi))])
                held.append([f, sl, k, name, [round((x[0] - te) * 1e9, 3) for x in inside]])
forced = []
for s in a.force:
    f, sl, k = s.split(",")
    f, k = int(f), int(k)
    name = ("o%snp" if k == 0 else "o%sp") % sl
    te = ts[f] + (k + 1) * T
    lo, hi = te - 3e-9, te + 1.0e-9
    orig = level_at(ev[name], te - 0.6e-9)
    forced.append({"frame": f, "slice": sl, "decision": k, "signal": name, "window_s": [lo, hi],
                   "original_level_at_strobe": orig})
    e = ev[name]
    before = [x for x in e if x[0] < lo]
    after = [x for x in e if x[0] > hi]
    ev[name] = before + [(lo, 0), (hi, level_at(e, hi))] + after
os.makedirs(os.path.join(HERE, "vec"), exist_ok=True)
os.makedirs(os.path.join(SAR, "sim", "vec"), exist_ok=True)
# Verilog stimulus: merged, time-ordered absolute events (ns, 1 ps resolution)
allev = []
for k in ("mclk", "oap", "oanp", "obp", "obnp", "oan", "oann", "obn", "obnn"):
    for te, x in ev[k]:
        allev.append((round(te * 1e12), k, x))
allev.sort()
L = ["// generated by sar/tb/vec_extract.py from run %s (case %s); do not edit" % (a.run, a.case)]
L.append("initial begin")
for k in ("mclk", "oap", "oanp", "obp", "obnp", "oan", "oann", "obn", "obnn"):
    L.append("    %s = 1'b%d;" % (k, ev[k][0][1]))
tprev = 0
for tp, k, x in allev:
    if tp == 0:
        continue
    if tp > tprev:
        L.append("    #%.3f;" % ((tp - tprev) / 1000.0))
        tprev = tp
    L.append("    %s = 1'b%d;" % (k, x))
L.append("end")
open(os.path.join(HERE, "vec", a.case + "_stim.vh"), "w").write("\n".join(L) + "\n")
# schedule for the ctrl model: tick index of each frame start (clk edge n at n T), type 0 = encoder, 1 = current
S = ["// generated by sar/tb/vec_extract.py; frame start ticks and types",
     "localparam integer NFR = %d;" % nfr, "localparam integer TEND_PS = %d;" % round(tend * 1e12)]
S.append("integer fr_tick [0:%d];" % (nfr - 1))
S.append("integer fr_type [0:%d];" % (nfr - 1))
S.append("initial begin")
for f, c in enumerate(a.frames):
    S.append("    fr_tick[%d] = %d; fr_type[%d] = %d;" % (f, round(ts[f] / T), f, 1 if c == "c" else 0))
S.append("end")
open(os.path.join(HERE, "vec", a.case + "_sched.vh"), "w").write("\n".join(S) + "\n")
# PWL for the SAR-only behavioural deck (20 ps edges; forced windows at 0.5 V)
P = ["* generated by sar/tb/vec_extract.py from run %s (case %s); do not edit" % (a.run, a.case)]
for k in ("mclk", "oap", "oanp", "obp", "obnp", "oan", "obn"):
    pts = []
    e = ev[k]
    fw = [x for x in forced if x["signal"] == k]
    v0 = 1.2 * e[0][1]
    pts.append((0.0, v0))
    for te, x in e[1:]:
        lvl = 1.2 * x
        inwin = [w for w in fw if abs(te - w["window_s"][0]) < 1e-15]
        if inwin:
            lvl = 0.5
        pts.append((te - 10e-12, pts[-1][1]))
        pts.append((te + 10e-12, lvl))
    s = " ".join("%.6e %.4g" % p for p in pts)
    P.append("V%s %s 0 PWL(%s)" % (k, k, s))
open(os.path.join(SAR, "sim", "vec", a.case + "_pwl.inc"), "w").write("\n".join(P) + "\n")
info = {"run": a.run, "case": a.case, "frames": a.frames, "T_s": T, "F_s": F, "T0_s": T0, "ts_s": ts, "tend_s": tend,
        "threshold_V": TH, "forced": forced, "strobe_hold": held, "n_edges": {k: len(v) for k, v in ev.items()}}
json.dump(info, open(os.path.join(HERE, "vec", a.case + ".json"), "w"), indent=1)
print(json.dumps({k: info[k] for k in ("case", "frames", "forced", "strobe_hold", "n_edges")}))
