#!/usr/bin/env python3
"""T2j: write sar/sim/tb_gl_mux.cir, the r5 mux-sequence deck (as sar/sim/tb_beh_mux.cir: frames e c e e, full
analog core, option 3c reference with the r1_bgr model) with the gate-level r1_adc_sar (PDK cell transistor
netlists, sar/tools/v2spice.py) in place of the behavioural r1_sar5_logic, and the r1_gate frame protocol as ideal
sources in place of the ideal trk / win / stb / lat timing:
  clk30 as the r5 timing (rising edges at n T); por_n low until 50 ns; start-up hold adc_hold ticks 3..5;
  frame f at tick 18 + 22 f: adc_start one tick, adc_hold (e) or is_smp (c) from the edge to edge 15 (r1_ctrl sees
  valid at E15 and releases there); cur_trk from 10 ticks before the current frame to one tick after its start.
  Every ctrl edge is 0.3 ns after the clk edge (clock-to-q, as the _cq decks), 50 ps transitions.
The analog core is r1_adc5_core of schematic/r1_adc_r5.spice instance by instance, without XSAR.
usage: gen_gl_deck.py <gl subckt spice (sar/tools/v2spice.py output; read for the port order)> [frames]
Substitutions left in the deck: CORNER TEMP VDD SAVELIST RAW GLNET (the subcircuit file).
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ADC = os.path.dirname(os.path.dirname(HERE))
gl = sys.argv[1]
frames = sys.argv[2] if len(sys.argv) > 2 else "ecee"
T = 1e9 / 30e6          # ns
ports = None
for l in open(gl if os.path.isabs(gl) else os.path.join(ADC, gl)):
    if l.startswith(".subckt r1_adc_sar_gl"):
        ports = l.split()[2:]
nets = []
for p in ports:
    m = re.fullmatch(r"(cpa|cna|cpb|cnb)_(\d+)", p)
    if m:
        nets.append(m.group(1) + m.group(2))
    elif p == "VDD":
        nets.append("vdd")
    elif p == "VSS":
        nets.append("0")
    elif re.fullmatch(r"adc_raw_[ab]_\d+", p):
        nets.append(p)
    else:
        nets.append(p)


def pwl(name, segs):
    """segs: list of (t_on_ns, t_off_ns) high intervals"""
    pts = ["0 0"]
    for a, b in segs:
        pts += ["%.4fn 0" % a, "%.4fn VDD" % (a + 0.05), "%.4fn VDD" % b, "%.4fn 0" % (b + 0.05)]
    return "V%s %s 0 PWL(%s)" % (name, name, " ".join(pts))


cq = 0.3
edge = lambda n: n * T + cq
start, hold, smp, cur = [], [], [(0, 0)], []
hold.append((edge(3), edge(5)))
for f, c in enumerate(frames):
    n0 = 18 + 22 * f
    start.append((edge(n0), edge(n0 + 1)))
    (smp if c == "c" else hold).append((edge(n0), edge(n0 + 15)))
    if c == "c":
        cur.append((edge(n0 - 10), edge(n0 + 1)))
smp = [s for s in smp if s[1] > s[0]]
L = ["* sar/sim/tb_gl_mux.cir -- generated by sar/sim/gen_gl_deck.py (T2j, D21); do not edit.",
     "* r5 mux-sequence deck (frames %s) with the gate-level r1_adc_sar (GLNET) and the r1_gate protocol." % frames,
     "* Substitutions: CORNER TEMP VDD SAVELIST RAW GLNET.",
     ".lib /foss/pdks/ihp-sg13g2/libs.tech/ngspice/models/cornerMOSlv.lib CORNER",
     ".lib /foss/pdks/ihp-sg13g2/libs.tech/ngspice/models/cornerCAP.lib cap_typ",
     ".lib /foss/pdks/ihp-sg13g2/libs.tech/ngspice/models/cornerMOShv.lib CORNER",
     ".lib /foss/pdks/ihp-sg13g2/libs.tech/ngspice/models/cornerRES.lib res_typ",
     ".include schematic/r1_adc_r5.spice",
     ".include /foss/pdks/ihp-sg13g2/libs.ref/sg13g2_stdcell/spice/sg13g2_stdcell.spice",
     ".include GLNET",
     ".temp TEMP",
     "* options as the r5 decks without 'klu': with the cell netlists the KLU operating point fails (run",
     "* t2j-ms-e-tt-c: timestep too small at vbg); the default SPARSE solver finds it",
     ".option reltol=1e-4 vntol=1e-6 abstol=1e-12 method=trap seed=1",
     "Vdd vdd 0 VDD",
     "Vdda vdda 0 3.3",
     "Vbgi vbgw 0 DC 1.045 TRNOISE(0.0004646 4.73e-08 0 0)",
     "Vbgf vbgi vbgw DC 0 TRNOISE(0 4.73e-08 1.15 1.285e-05)",
     "Rbg vbgi vbg 190k",
     "XCF vbg 0 r1_reffilt5 w=82u",
     "Ibref vdda nbr 5u",
     "XREF vbg vref vrefl nbr vdda 0 r1_refbuf5 ndec=4 ndecl=2",
     "Vtvrefa vrefa vref 0", "Vtvrefb vrefb vref 0", "Vtvrefla vrefla vrefl 0", "Vtvreflb vreflb vrefl 0",
     "Vcme vcme 0 0.6", "Vcmi vcmi 0 0.6",
     "Vsin vsin 0 PWL(0 0.40 1.012u 0.40 1.022u -0.40 2.352u -0.40 2.362u 0.72 6u 0.72)",
     "Visa visa 0 0.85",
     "Esp sinp vcme vsin 0 0.5", "Esn sinn vcme vsin 0 -0.5", "Ecp cosp vcme vsin 0 -0.5", "Ecn cosn vcme vsin 0 0.5",
     "Eap isap vcmi visa 0 0.5", "Ean isan vcmi visa 0 -0.5", "Ebp isbp vcmi visa 0 -0.5", "Ebn isbn vcmi visa 0 0.5",
     "* clk30 as sim/r5/gen_timing_r5.py",
     "Vclk30 clk 0 PULSE(0 VDD %.9gn 50p 50p %.9gn %.9gn)" % (T, T / 2 - 0.05, T),
     "Vpor por_n 0 PWL(0 0 50n 0 50.05n VDD)",
     pwl("adc_start", start), pwl("adc_hold", hold), pwl("is_smp", smp), pwl("cur_trk", cur),
     "Vsel adc_sel 0 0",
     "* analog core: r1_adc5_core without XSAR",
     "XCKG clk mclk mclkb vdd 0 r1_cmp4_clkgen",
     "XTHA sinp sinn isap isan trka0 trka1 topap topan " + " ".join("cpa%d" % k for k in range(12, -1, -1)) + " "
     + " ".join("cna%d" % k for k in range(12, -1, -1)) + " vdd vrefa vrefla 0 r1_th4",
     "XCBIAS vbp vdd 0 r1_cmp4_bias",
     "XCBIASN vbn vdd 0 r1_cmp5n_bias",
     "XCMPA topap topan clka clkab oap oan vbp vdd 0 r1_cmp4",
     "XCMPNA topap topan clkna clknab oanp oann vbn vdd 0 r1_cmp5n",
     "XTHB cosp cosn isbp isbn trkb0 trkb1 topbp topbn " + " ".join("cpb%d" % k for k in range(12, -1, -1)) + " "
     + " ".join("cnb%d" % k for k in range(12, -1, -1)) + " vdd vrefb vreflb 0 r1_th4",
     "XCMPB topbp topbn clkb clkbb obp obn vbp vdd 0 r1_cmp4",
     "XCMPNB topbp topbn clknb clknbb obnp obnn vbn vdd 0 r1_cmp5n",
     "* gate-level SAR logic and sequencer",
     "XSAR " + " ".join(nets) + " r1_adc_sar_gl",
     ".control", "set num_threads=1", "save SAVELIST", "tran 1n 3.31u 0 0.2n", "write RAW/sar.raw", ".endc", ".end"]
open(os.path.join(HERE, "tb_gl_mux.cir"), "w").write("\n".join(L) + "\n")
sv = ["v(%s)" % n for n in "clk mclk por_n adc_hold is_smp adc_start cur_trk adc_valid_a adc_valid_b oap oan oanp oann obp obn obnp obnn clka clkab clkna clknab clkb clkbb clknb clknbb trka0 trka1 trkb0 trkb1 topap topan topbp topbn vrefa vrefla".split()]
sv += ["v(adc_raw_%s_%d)" % (s, k) for s in "ab" for k in range(14)]
sv += ["v(c%s%s%d)" % (p, s, k) for s in "ab" for p in "pn" for k in range(13)]
sv += ["i(vdd)", "i(vdda)"]
open(os.path.join(HERE, "save_gl.inc"), "w").write(" ".join(sv) + "\n")
print("wrote tb_gl_mux.cir, save_gl.inc; ports", len(ports))
