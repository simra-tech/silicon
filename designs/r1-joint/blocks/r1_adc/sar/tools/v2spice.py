#!/usr/bin/env python3
"""T2j: convert the LibreLane gate-level netlist of r1_adc_sar (final pnl.v or nl.v) into a SPICE subcircuit that
uses the PDK standard-cell transistor netlists (libs.ref/sg13g2_stdcell/spice/sg13g2_stdcell.spice).

usage: v2spice.py <netlist.v> <sg13g2_stdcell.spice> <out.spice>
Subcircuit: .subckt r1_adc_sar_gl <signal ports in Verilog order, buses expanded MSB first> VDD VSS (pnl.v lists
VDD / VSS among its ports; they are moved to the end)
Net names: bus bits a[3] -> a_3; escaped identifiers lose the backslash; '.' and '$' -> '_'.
Cells without a SPICE subcircuit (fill cells, no devices) are skipped and listed in a comment; instance pins that
are not in the cell's port list are an error. VDD / VSS of a cell connect to the subcircuit supplies when the
Verilog instance has no supply pins (nl.v).
"""
import re, sys

vf, lib, out = sys.argv[1:4]
# antenna diode cells: a reverse-biased diode only (the PDK 'dantenna' model, whose discontinuity stalls ngspice
# transients, project note on pad diodes); left out of the simulation netlist and listed in the header
NOSIM = {"sg13g2_antennanp"}
cells = {}
for l in open(lib):
    m = re.match(r"\.subckt\s+(\S+)\s+(.*)", l, re.I)
    if m:
        cells[m.group(1)] = m.group(2).split()


def nn(s):
    s = s.strip()
    if s.startswith("\\"):
        s = s[1:]
    s = s.replace("[", "_").replace("]", "").replace(".", "_").replace("$", "_")
    return s


txt = open(vf).read()
txt = re.sub(r"//.*", "", txt)
txt = re.sub(r"/\*.*?\*/", "", txt, flags=re.S)
mod = re.search(r"module\s+(\S+)\s*\((.*?)\);(.*?)endmodule", txt, re.S)
body = mod.group(3)
# port declarations with ranges
ports = []
order = [p.strip() for p in mod.group(2).split(",")]
decl = {}
for m in re.finditer(r"\b(input|output|inout)\s+(?:wire\s+)?(\[(\d+):(\d+)\])?\s*([^;]+);", body):
    for n in m.group(5).split(","):
        n = n.strip()
        decl[n] = (int(m.group(3)), int(m.group(4))) if m.group(2) else None
for p in order:
    p = p.split()[-1]
    r = decl.get(p)
    if r is None:
        ports.append(nn(p))
    else:
        hi, lo = r
        rng = range(hi, lo - 1, -1) if hi >= lo else range(hi, lo + 1)
        ports += ["%s_%d" % (p, i) for i in rng]
# assigns (yosys may leave buffers as assigns)
assigns = re.findall(r"assign\s+(\S+)\s*=\s*([^;]+);", body)
lines = []
skipped = {}
ninst = 0
for m in re.finditer(r"^\s*(sg13g2_\w+)\s+(\S+)\s*\((.*?)\)\s*;", body, re.S | re.M):
    cell, inst, conn = m.group(1), m.group(2), m.group(3)
    pins = dict((a, nn(b)) for a, b in re.findall(r"\.(\w+)\s*\(\s*([^()]*?)\s*\)", conn))
    if cell not in cells or cell in NOSIM:
        skipped[cell] = skipped.get(cell, 0) + 1
        continue
    args = []
    for p in cells[cell]:
        if p in pins and pins[p]:
            args.append(pins[p])
        elif p in ("VDD", "VSS"):
            args.append(p)
        else:
            args.append("nc_%s_%s" % (nn(inst), p))
    extra = set(pins) - set(cells[cell])
    if extra:
        sys.exit("instance %s (%s): pins %s not in the cell" % (inst, cell, sorted(extra)))
    lines.append("X%s %s %s" % (nn(inst), " ".join(args), cell))
    ninst += 1
for a, b in assigns:
    b = b.strip()
    if re.fullmatch(r"1'b[01]", b):
        lines.append("V%s %s %s 0" % (nn(a), nn(a), "VSS" if b.endswith("0") else "VDD"))
    else:
        lines.append("R%s %s %s 1m" % (nn(a), nn(a), nn(b)))
hdr = ["* r1_adc_sar_gl: generated by sar/tools/v2spice.py from %s (%d cell instances, %d assigns)"
       % (vf.split("/")[-1], ninst, len(assigns)),
       "* skipped cells (no SPICE subcircuit, or antenna diode only): %s" % (", ".join("%s x%d" % kv for kv in sorted(skipped.items())) or "none"),
       ".subckt r1_adc_sar_gl %s" % " ".join([p for p in ports if p not in ("VDD", "VSS")] + ["VDD", "VSS"])]
open(out, "w").write("\n".join(hdr + lines + [".ends r1_adc_sar_gl", ""]))
print("ports %d instances %d assigns %d skipped %s" % (len(ports), ninst, len(assigns), skipped))
