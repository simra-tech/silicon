#!/usr/bin/env python3
"""Write sim/tb_cdac_mc.cir: CDAC capacitor-mismatch Monte Carlo, N independent array pairs in one deck.

Each pair (side P, side N) is an r1_cdac_side_mc instance (one cap_cmim per unit, mm_ok=1, section
cap_typ_mismatch), so every unit draws its own agauss value (1 %/sqrt(um2), S4). The bit weight of capacitor k
is the top-node response to a VREF step on bottom plate k with all other bottom plates held: a linear
capacitive divider, solved here as 11 AC analyses at 1 kHz (one per bottom plate, AC magnitude 1 V; top and
lsb nodes float behind 1e15 ohm). weight_k = VREF * Re(v(top)). An extra top-node load C_par can be added.
post_cdac_mc.py turns the weights into the SAR transfer, DNL and INL per sample.
(Earlier transient version abandoned: run cdac-mc50-tt stalled at 0.23 ps on the 1-ohm reset switches.)
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
NB = 11


def main(n=50, cpar_f=0.0):
    L = ["* tb_cdac_mc.cir (generated by gen_tb_cdac_mc.py) -- CDAC mismatch MC, %d samples x 2 sides" % n,
         ".lib /foss/pdks/ihp-sg13g2/libs.tech/ngspice/models/cornerCAP.lib cap_typ_mismatch",
         ".include schematic/r1_adc.spice"]
    for k in range(NB - 1, -1, -1):
        L.append("Vb%d b%d 0 DC 0 AC 0" % (k, k))
    bl = " ".join("b%d" % k for k in range(NB - 1, -1, -1))
    for i in range(n):
        for s in ("p", "n"):
            L.append("X%s%d t%s%d l%s%d %s r1_cdac_side_mc mm=1" % (s, i, s, i, s, i, bl))
            L.append("R%st%d t%s%d 0 1e15" % (s, i, s, i))
            L.append("R%sl%d l%s%d 0 1e15" % (s, i, s, i))
            if cpar_f > 0:
                L.append("C%spar%d t%s%d 0 %gf" % (s, i, s, i, cpar_f))
    L.append(".control")
    L.append("set wr_singlescale")
    vecs = " ".join("v(t%s%d)" % (s, i) for i in range(n) for s in ("p", "n"))
    for k in range(NB - 1, -1, -1):
        L.append("alter vb%d acmag=1" % k)
        L.append("ac lin 1 1k 1k")
        L.append("wrdata @RAW@/w_b%d.txt %s" % (k, vecs))
        L.append("alter vb%d acmag=0" % k)
    L.append(".endc")
    L.append(".end")
    with open(os.path.join(HERE, "tb_cdac_mc.cir"), "w") as f:
        f.write("\n".join(L) + "\n")
    print("wrote tb_cdac_mc.cir (%d samples)" % n)


if __name__ == "__main__":
    main(int(sys.argv[1]) if len(sys.argv) > 1 else 50)
