#!/usr/bin/env python3
"""Write sim/r4/r1_adc_timing_r4_<tag>.inc: ideal timing sources standing in for r1_ctrl, revision 4 (D18).

D18 frame: 22 ticks at 30 MHz (T = 33.33 ns, frame F = 733.3 ns). Each slice converts once per frame:
14 decisions at one per tick, then >= 250 ns track. Slice A samples at tsA = T0 + f F (T0 = 600 ns = 18 T);
slice B at tsB = tsA + N T (stagger N ticks, R2-4 option 1; N = 0: common sampling edge).
Per slice X and frame:
  * clk30: 50 % duty, rising edges on the tick grid (T0 is on the grid). Each rising edge is the decision strobe
    of r1_ctrl and fires the comparator reset one-shot r1_cmp4_clkgen inside the ADC (no other sub-tick edge).
  * winX: tsX + 1 ns .. tsX + 14 T + 1 ns (comparator enabled for decisions 0..13; both edges fall inside a
    reset pulse of the one-shot).
  * stbX_k (k = 0..13): rising at tsX + (k + 1) T - 0.6 ns (the decision-k register samples the comparator just
    before the clk30 edge that resets it; the CDAC then switches at the edge). Width 0.3 ns.
  * latX: tsX + 14 T + 0.5 ns (conversion = 14 ticks <= 17, INTERFACES.md).
  * trkX0 / trkX1 (in0 = SIN/COS, in1 = ISA/ISB): rising at tsX - 8 T + 6 ns (2 ns edge, 6 ns off the clock grid:
    an edge on the grid stopped ngspice in revision 3), falling at tsX. Track window 258.7 ns >= 250 ns.
    Slice B rising edge +1.5 ns when N = 0 (coincident edges stopped ngspice in revision 3).
  * mux decks: frame type per frame, 'e' (encoder, trkX0) or 'c' (stolen current frame, trkX1).
  * _cq variants: track falling edge 0.3 ns after the clk30 edge (clock-to-q of the r1_ctrl flip-flop).
usage: gen_timing_r4.py  (writes the set used by the revision-4 decks)
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
T = 1.0 / 30e6
F = 22 * T
T0 = 18 * T
TR = 50e-12
ND = 14
TRK = 8 * T - 6e-9
TRR = 2e-9


def lines(vdd, n_stag, frames=None, nfr=None, dq=0.0):
    hi = vdd
    tag = "mux" if frames else "enc"
    L = ["* r1_adc_timing_r4 (generated by sim/r4/gen_timing_r4.py) -- IDEAL timing sources (stand-in for r1_ctrl), D18",
         "* T = %.6g s, frame F = 22 T = %.6g s, first slice-A sampling edge t0 = %.6g s, stagger N = %g ticks, VDD %g V, %s"
         % (T, F, T0, n_stag, vdd, ("frames " + "".join(frames)) if frames else "encoder frames only"),
         ".param t_cyc=%.9g t_frame=%.9g t_0=%.9g n_stag=%g" % (T, F, T0, n_stag)]
    L.append("Vclk30 clk30 0 PULSE(0 %g %.9g %g %g %.9g %.9g)" % (hi, T, TR, TR, T / 2 - TR, T))
    for ch, off in (("a", 0.0), ("b", n_stag * T)):
        ts0 = T0 + off
        L.append("Vwin%s win%s 0 PULSE(0 %g %.9g %g %g %.9g %.9g)" % (ch, ch, hi, ts0 + 1e-9, TR, TR, ND * T - TR, F))
        for k in range(ND):
            L.append("Vstb%s%d stb%s%d 0 PULSE(0 %g %.9g %g %g %.9g %.9g)" % (ch, k, ch, k, hi, ts0 + (k + 1) * T - 0.6e-9, TR, TR, 0.3e-9, F))
        L.append("Vlat%s lat%s 0 PULSE(0 %g %.9g %g %g %.9g %.9g)" % (ch, ch, hi, ts0 + ND * T + 0.5e-9, TR, TR, 1e-9, F))
        db = 1.5e-9 if (ch == "b" and n_stag == 0) else 0.0
        if not frames:
            L.append("Vtrk%s0 trk%s0 0 PULSE(0 %g %.9g %g %g %.9g %.9g)" % (ch, ch, hi, ts0 - TRK + db, TRR, TR, TRK - TRR - TR - db, F))
            L.append("Vtrk%s1 trk%s1 0 0" % (ch, ch))
        else:
            for inp, kind in (("0", "e"), ("1", "c")):
                pts = ["0 0"]
                for f, fk in enumerate(frames):
                    if fk != kind:
                        continue
                    ts = ts0 + f * F + dq
                    r0 = ts - dq - TRK + db
                    pts += ["%.9g 0" % r0, "%.9g %g" % (r0 + TRR, hi), "%.9g %g" % (ts - TR, hi), "%.9g 0" % ts]
                L.append("Vtrk%s%s trk%s%s 0 PWL(%s)" % (ch, inp, ch, inp, " ".join(pts)))
    return L


def write(fn, L):
    with open(os.path.join(HERE, fn), "w") as f:
        f.write("\n".join(L) + "\n")


def main():
    out = []
    for vtag, vdd in (("", 1.2), ("_vdd108", 1.08), ("_vdd132", 1.32)):
        for n in (0, 1, 2, 4, 7, 8):
            fn = "r1_adc_timing_r4_n%d%s.inc" % (n, vtag)
            write(fn, lines(vdd, n))
            out.append(fn)
        for n in (0, 1, 2, 4, 7, 8):
            fn = "r1_adc_timing_r4_mux_n%d%s.inc" % (n, vtag)
            write(fn, lines(vdd, n, frames=list("ecee")))
            out.append(fn)
    # _cq: sampling (track falling) edge 0.3 ns after the clk30 edge (clock-to-q of the r1_ctrl flip-flop). The
    # full-core mux deck stopped at the first sampling edge with the edge on the clock grid (run r4-isa-tt).
    for vtag, vdd in (("", 1.2), ("_vdd108", 1.08), ("_vdd132", 1.32)):
        fn = "r1_adc_timing_r4_mux_n0_cq%s.inc" % vtag
        write(fn, lines(vdd, 0, frames=list("ecee"), dq=0.3e-9))
        out.append(fn)
    print("wrote %d files: %s ..." % (len(out), out[0]))


if __name__ == "__main__":
    main()
