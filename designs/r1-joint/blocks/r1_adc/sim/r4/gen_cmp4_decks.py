#!/usr/bin/env python3
"""Write the revision-4 comparator decks (sim/r4/tb_cmp4_mem.cir, sim/r4/tb_cmp4_noise.cir).

Question (R2-3, revision 4): which integration capacitor and bias give <= 60 uV rms input noise at ss / 125 C /
1.08 V while every decision resolves before the next clk30 edge (one decision per tick, D18)?
Clock: ideal clk30 (33.33 ns, 50 % duty) -> r1_cmp4_clkgen (transistor level) -> mclk; the comparators see mclk
through a smooth threshold buffer (stands in for the XSPICE bridge of the SAR logic, 80 ps edges).
mem deck: per tick the input alternates +30 mV, -@ASM@ (memory test of revision 3, now also the decision-time
test); the small decision must be 0. CM 0.6 / 0.35 / 0.1 V. Each variant has its own bias and supply ammeter.
noise deck: first stage only (r1_cmp4_s1), dip/din held at 0.3 V, quasi-static .noise (method A of revision 2).
Variants: name -> (wcap, rbl, wr[, extra instance parameters]).
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
T = 1000 / 30.0      # ns
SETS = {"a": {"v32": ("32u", "160u", "8u"), "v48": ("48u", "160u", "12u"), "v64": ("64u", "160u", "16u"),
              "v64r": ("64u", "200u", "16u"), "v80": ("80u", "160u", "20u"), "v96": ("96u", "160u", "24u")},
        "b": {"w64": ("64u", "130u", "16u", "wi=64u ngi=16"), "w80": ("80u", "130u", "20u", "wi=64u ngi=16"),
              "w96": ("96u", "130u", "24u", "wi=64u ngi=16"), "v96r": ("96u", "130u", "24u"),
              "v112": ("112u", "130u", "28u"), "w112": ("112u", "130u", "28u", "wi=64u ngi=16")}}
SET = os.environ.get("CMP4_SET", "a")
VARIANTS = SETS[SET]
SFX = "" if SET == "a" else "_" + SET
HDR = [".lib /foss/pdks/ihp-sg13g2/libs.tech/ngspice/models/cornerMOSlv.lib @CORNER@",
       ".lib /foss/pdks/ihp-sg13g2/libs.tech/ngspice/models/cornerCAP.lib cap_typ",
       ".lib /foss/pdks/ihp-sg13g2/libs.tech/ngspice/models/cornerRES.lib res_typ",
       ".include schematic/r1_adc_r4.spice", ".temp @TEMP@"]
NT = 10   # ticks simulated


def extra(v):
    return VARIANTS[v][3] if len(VARIANTS[v]) > 3 else ""


def mem():
    L = ["* tb_cmp4_mem.cir (generated by sim/r4/gen_cmp4_decks.py) -- r1_cmp4 variants, one decision per tick,"
         " clock from r1_cmp4_clkgen, alternating +30 mV / -ASM input"] + HDR
    L += [".option reltol=1e-4 vntol=1e-7 abstol=1e-13 method=gear", "Vdd vdd 0 @VDD@",
          "Vclk30 clk30 0 PULSE(0 @VDD@ 2n 50p 50p %.6gn %.6gn)" % (T / 2 - 0.05, T),
          "XCKG clk30 mclk mclkb vdd 0 r1_cmp4_clkgen",
          "Bclk clk 0 v=@VDD@*0.5*(1+tanh(25*(v(mclk)-0.6)))",
          "Bclkb clkb 0 v=@VDD@*0.5*(1-tanh(25*(v(mclk)-0.6)))",
          # +30 mV in even ticks, -ASM in odd ticks; changes 1 ns before the clk30 edge (CDAC switching instant)
          "Vd vd 0 PULSE(0.03 -@ASM@ %.6gn 0.2n 0.2n %.6gn %.6gn)" % (2 + T - 1.2, T - 0.2, 2 * T)]
    sv = ["v(clk30)", "v(mclk)", "v(vd)", "i(vdd)"]
    for v in VARIANTS:
        wc, rb, wr = VARIANTS[v][:3]
        L.append("V_%s vdd_%s vdd 0" % (v, v))
        L.append("XB%s vbp%s vdd_%s 0 r1_cmp4_bias rbl=%s" % (v, v, v, rb))
        for cm, tag in ((0.6, "h"), (0.35, "m"), (0.1, "l")):
            n = "%s%s" % (v, tag)
            L.append("Bp%s ip%s 0 v=%g+v(vd)/2" % (n, n, cm))
            L.append("Bn%s in%s 0 v=%g-v(vd)/2" % (n, n, cm))
            L.append("X%s ip%s in%s clk clkb op%s on%s vbp%s vdd_%s 0 r1_cmp4 wcap=%s wr=%s %s" % (n, n, n, n, n, v, v, wc, wr, extra(v)))
            sv += ["v(op%s)" % n, "v(on%s)" % n]
        sv.append("i(v_%s)" % v)
    L += [".control", "set num_threads=1", "save " + " ".join(sv),
          "tran 5p %.6gn 0 20p" % (2 + NT * T), "write @RAW@/mem.raw", ".endc", ".end"]
    open(os.path.join(HERE, "tb_cmp4_mem%s.cir" % SFX), "w").write("\n".join(L) + "\n")


def noise():
    L = ["* tb_cmp4_noise.cir (generated by sim/r4/gen_cmp4_decks.py) -- r1_cmp4 first stage, quasi-static noise"] + HDR
    L += ["Vdd vdd 0 @VDD@", "Vclkb clkb 0 0", "Vx vx 0 @VX@"]
    ctl = [".control", "set num_threads=1", "set wr_singlescale", "set wr_vecnames"]
    for v in VARIANTS:
        L.append("XB%s vbp%s vdd 0 r1_cmp4_bias rbl=%s" % (v, v, VARIANTS[v][1]))
        L.append("Vinp%s inp%s 0 DC @VCM@ AC 1" % (v, v))
        L.append("Vinn%s inn%s 0 DC @VCM@" % (v, v))
        L.append("X%s inp%s inn%s dp%s dn%s clkb vbp%s vdd 0 r1_cmp4_s1 %s" % (v, v, v, v, v, v, extra(v)))
        L.append("Vdp%s dp%s vx 0" % (v, v))
        L.append("Vdn%s dn%s vx 0" % (v, v))
        L.append("H%s out%s 0 poly(2) Vdp%s Vdn%s 0 1 -1" % (v, v, v, v))
    for v in VARIANTS:
        ctl += ["op", "noise v(out%s) vinp%s dec 20 1e3 1e11" % (v, v), "setplot noise1",
                "wrdata @RAW@/noise_%s.txt inoise_spectrum onoise_spectrum" % v, "destroy all", "reset"]
    L += ctl + [".endc", ".end"]
    open(os.path.join(HERE, "tb_cmp4_noise%s.cir" % SFX), "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    mem()
    noise()
    print("wrote tb_cmp4_mem%s.cir, tb_cmp4_noise%s.cir" % (SFX, SFX))
