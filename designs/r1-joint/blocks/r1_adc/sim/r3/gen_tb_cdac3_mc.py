#!/usr/bin/env python3
"""Write sim/r3/tb_cdac3_mc.cir: revision-3 CDAC MIM-mismatch Monte Carlo (14 decisions, 13 caps per side) (same method as sim/gen_tb_cdac_mc.py).

N independent array pairs (r1_cdac3_side_mc, one cap_cmim per unit, mm_ok=1, cap_typ_mismatch). The weight of
bottom plate k (k = 12..0) is the top-node response to a 1 V AC step on that plate (12 AC analyses at 1 kHz,
top and lsb nodes float behind 1e15 ohm); post_cdac2_mc.py scales by VREF = 1.0 V. Optional top-node parasitic
@CPAR@ (fF, nominal comparator input + switches) and lsb-node parasitic @CPLSB@ (fF).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
NB = 13


def main(n=50):
    L = ["* tb_cdac3_mc.cir (generated by sim/r3/gen_tb_cdac3_mc.py) -- revision-3 CDAC mismatch MC, %d samples x 2 sides" % n,
         ".lib /foss/pdks/ihp-sg13g2/libs.tech/ngspice/models/cornerCAP.lib cap_typ_mismatch",
         ".include schematic/r1_adc_r3.spice"]
    for k in range(NB - 1, -1, -1):
        L.append("Vb%d b%d 0 DC 0 AC 0" % (k, k))
    bl = " ".join("b%d" % k for k in range(NB - 1, -1, -1))
    for i in range(n):
        for s in ("p", "n"):
            L.append("X%s%d t%s%d l%s%d %s r1_cdac3_side_mc mm=1" % (s, i, s, i, s, i, bl))
            L.append("R%st%d t%s%d 0 1e15" % (s, i, s, i))
            L.append("R%sl%d l%s%d 0 1e15" % (s, i, s, i))
            L.append("C%spar%d t%s%d 0 @CPAR@f" % (s, i, s, i))
            L.append("C%splsb%d l%s%d 0 @CPLSB@f" % (s, i, s, i))
    L.append(".control")
    L.append("set wr_singlescale")
    vecs = " ".join("v(t%s%d)" % (s, i) for i in range(n) for s in ("p", "n"))
    for k in range(NB - 1, -1, -1):
        L.append("alter vb%d acmag=1" % k)
        L.append("ac lin 1 1k 1k")
        L.append("wrdata @RAW@/w_b%d.txt %s" % (k, vecs))
        L.append("alter vb%d acmag=0" % k)
    L += [".endc", ".end"]
    open(os.path.join(HERE, "tb_cdac3_mc.cir"), "w").write("\n".join(L) + "\n")
    print("wrote tb_cdac3_mc.cir (%d samples)" % n)


if __name__ == "__main__":
    main(int(sys.argv[1]) if len(sys.argv) > 1 else 50)
