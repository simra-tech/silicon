#!/usr/bin/env python3
"""Write sim/r3/r1_adc_timing_r3*.inc: ideal timing sources standing in for r1_ctrl, revision 3 (D17).

36-tick frame at 30 MHz (T = 33.33 ns) = two 18-tick slots. Slot s has its sampling edge at ts = T0 + s * 18 T
(falling edge of the track signals of BOTH slices: SIN/COS in even slots, ISA/ISB in odd slots).
Both slices convert in parallel: 14 decisions at two per tick (half tick H = 16.67 ns). Decision k:
comparator evaluates (mclk = 1) from ts + k H + 1.0 ns for 13.5 ns; strobe stb_k at ts + k H + 14.0 ns (13.0 ns
after the start of evaluation); 3.2 ns of comparator reset and CDAC settling before the next evaluation.
lata = latb at ts + 13 H + 16.5 ns (7.0 ticks after the edge): conversion <= 17 ticks (INTERFACES.md).
Track window of every slot: ts - 10 T + 6 ns .. ts = 327 ns >= 250 ns (slice B 1.5 ns shorter) (INTERFACES.md), both slices.
In hardware the 13.5 / 3.2 ns split of each half tick needs a local delay cell in the ADC (not designed).
Files: r1_adc_timing_r3[_vdd108|_vdd132].inc  -- both slots sample in0 (SIN on A, COS on B): static/dynamic decks
       r1_adc_timing_r3_mux[...].inc          -- even slots in0 (SIN/COS), odd slots in1 (ISA/ISB): mux deck
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
T = 1.0 / 30e6
H = T / 2
SLOT = 18 * T
T0 = 600e-9
TR = 50e-12
ND = 14
TRK = 10 * T - 6e-9     # track starts 6 ns after a clk30 edge: starting on an mclk edge stopped ngspice (r3-smoke-tt-c)
TRR = 2e-9         # track-start (rising) edge; 50 ps and 1 ns edges both stopped ngspice at the track start (r3-smoke-tt-a/-b)
DB = 1.5e-9        # slice-B track start 1.5 ns after slice A (both edges coincident stopped ngspice; sampling edges stay common)


def lines(vdd, mux):
    L = ["* r1_adc_timing_r3%s.inc (generated by sim/r3/gen_timing_r3.py) -- IDEAL timing sources (stand-in for r1_ctrl)" % ("_mux" if mux else ""),
         "* T = %.6g s, slot = 18 T = %.6g s, frame = 36 T, first sampling edge t0 = %.6g s, VDD level %g V" % (T, SLOT, T0, vdd),
         ".param t_cyc=%.9g t_slot=%.9g t_0=%.9g" % (T, SLOT, T0)]
    hi = vdd
    td0 = T0 - TRK
    if mux:
        for nm, off in (("trka0", 0), ("trkb0", 0), ("trka1", SLOT), ("trkb1", SLOT)):
            db = DB if "b" in nm else 0.0
            L.append("V%s %s 0 PULSE(0 %g %.9g %g %g %.9g %.9g)" % (nm, nm, hi, td0 + off + db, TRR, TR, TRK - TRR - TR - db, 2 * SLOT))
    else:
        for nm in ("trka0", "trkb0"):
            db = DB if "b" in nm else 0.0
            L.append("V%s %s 0 PULSE(0 %g %.9g %g %g %.9g %.9g)" % (nm, nm, hi, td0 + db, TRR, TR, TRK - TRR - TR - db, SLOT))
        L.append("Vtrka1 trka1 0 0")
        L.append("Vtrkb1 trkb1 0 0")
    L.append("Vmclk mclk 0 PULSE(0 %g %.9g %g %g %.9g %.9g)" % (hi, T0 + 1e-9, TR, TR, 13.45e-9, H))
    for nm in ("wina", "winb"):
        L.append("V%s %s 0 PULSE(0 %g %.9g %g %g %.9g %.9g)" % (nm, nm, hi, T0, TR, TR, ND * H - TR, SLOT))
    for k in range(ND):
        L.append("Vstb%d stb%d 0 PULSE(0 %g %.9g %g %g %.9g %.9g)" % (k, k, hi, T0 + k * H + 14.0e-9, TR, TR, 1.5e-9, SLOT))
    for nm in ("lata", "latb"):
        L.append("V%s %s 0 PULSE(0 %g %.9g %g %g %.9g %.9g)" % (nm, nm, hi, T0 + (ND - 1) * H + 16.5e-9, TR, TR, 1.5e-9, SLOT))
    return L


def main():
    for tag, vdd in (("", 1.2), ("_vdd108", 1.08), ("_vdd132", 1.32)):
        for mux in (False, True):
            fn = "r1_adc_timing_r3%s%s.inc" % ("_mux" if mux else "", tag)
            with open(os.path.join(HERE, fn), "w") as f:
                f.write("\n".join(lines(vdd, mux)) + "\n")
    print("wrote r1_adc_timing_r3*.inc")


if __name__ == "__main__":
    main()
