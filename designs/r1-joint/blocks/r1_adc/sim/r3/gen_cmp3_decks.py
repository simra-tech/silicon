#!/usr/bin/env python3
"""Write the revision-3 comparator decks (sim/r3/tb_cmp3_tran.cir, sim/r3/tb_cmp3_noise.cir).

Question (R2-3): which integration capacitor and bias give <= 60 uV rms input noise at ss / 125 C / 1.08 V while
the decision stays inside the revision-3 strobe (evaluate 13.5 ns, strobe 13.0 ns after the start of evaluation,
half-tick decision period 16.67 ns) at tt, ss / 125 C / 1.08 V and ff / -40 C / 1.32 V?
Variants (set a, set b via CMP3_SET=b): name -> (wcap, bias). bias = ("i", "14u") ideal current (revision-2 bias) or ("r", rbl) rppd 1 um x rbl.
tran: +0.2 mV input at CM 0.6 / 0.35 / 0.1 V, decision clock of revision 3. Each variant has its own bias and its
own supply ammeter (V_<v>), so current per comparator pair is reported.
noise: first stage only (r1_cmp3_s1), dip/din held at VX, quasi-static .noise (method A of revision 2).
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SETS = {"a": {
    "i16": ("16u", ("i", "14u")),
    "i32": ("32u", ("i", "14u")),
    "r24a": ("24u", ("r", "80u")), "r24b": ("24u", ("r", "120u")),
    "r32a": ("32u", ("r", "80u")), "r32b": ("32u", ("r", "120u")), "r32c": ("32u", ("r", "160u")),
    "r40a": ("40u", ("r", "80u")), "r40b": ("40u", ("r", "120u")), "r40c": ("40u", ("r", "160u")),
}, "b": {
    # second sweep (after set a: resistor bias equalises t_dec over corners; noise at ss/125 C needs more C_int)
    "r56a": ("56u", ("r", "100u")), "r56b": ("56u", ("r", "115u")), "r56c": ("56u", ("r", "130u")),
    "r64a": ("64u", ("r", "100u")), "r64b": ("64u", ("r", "115u")), "r64c": ("64u", ("r", "130u")),
}, "c": {
    # third sweep (set b: at a fixed integration time the ss/125 C noise is limited by gm; more current and C)
    "r80a": ("80u", ("r", "75u")), "r80b": ("80u", ("r", "85u")),
    "r96a": ("96u", ("r", "65u")), "r96b": ("96u", ("r", "75u")),
    "w64a": ("64u", ("r", "85u"), "wi=64u ngi=16"), "w64b": ("80u", ("r", "75u"), "wi=64u ngi=16"),
}}
SET = os.environ.get("CMP3_SET", "a")
VARIANTS = SETS[SET]
HDR = [".lib /foss/pdks/ihp-sg13g2/libs.tech/ngspice/models/cornerMOSlv.lib @CORNER@",
       ".lib /foss/pdks/ihp-sg13g2/libs.tech/ngspice/models/cornerCAP.lib cap_typ",
       ".lib /foss/pdks/ihp-sg13g2/libs.tech/ngspice/models/cornerRES.lib res_typ",
       ".include schematic/r1_adc_r3.spice", ".temp @TEMP@"]
H = 1e-9 * 1000 / 60.0      # half tick 16.667 ns


def bias(v, vdd):
    w, b = VARIANTS[v][:2]
    if b[0] == "i":
        return "XB%s vbp%s %s 0 r1_cmp3_ibias ib=%s" % (v, v, vdd, b[1])
    return "XB%s vbp%s %s 0 r1_cmp3_bias rbw=1u rbl=%s" % (v, v, vdd, b[1])


def tran():
    L = ["* tb_cmp3_tran.cir (generated by sim/r3/gen_cmp3_decks.py) -- r1_cmp3 variants, decision dynamics, rev-3 clock"] + HDR
    L += [".option reltol=1e-4 vntol=1e-7 abstol=1e-13 method=gear", "Vdd vdd 0 @VDD@",
          "Vclk clk 0 PULSE(0 @VDD@ 1n 50p 50p 13.45n %.6gn)" % (H * 1e9),
          "Vclkb clkb 0 PULSE(@VDD@ 0 1n 50p 50p 13.45n %.6gn)" % (H * 1e9)]
    sv = []
    for v in VARIANTS:
        L.append("V_%s vdd_%s vdd 0" % (v, v))
        L.append(bias(v, "vdd_%s" % v))
        sv.append("v(vbp%s)" % v)
        for cm, tag in ((0.6, "h"), (0.35, "m"), (0.1, "l")):
            n = "%s%s" % (v, tag)
            L.append("Vp%s ip%s 0 %g" % (n, n, cm + 1e-4))
            L.append("Vn%s in%s 0 %g" % (n, n, cm - 1e-4))
            L.append("X%s ip%s in%s clk clkb op%s on%s vbp%s vdd_%s 0 r1_cmp3 wcap=%s %s" % (n, n, n, n, n, v, v, VARIANTS[v][0],
                     VARIANTS[v][2] if len(VARIANTS[v]) > 2 else ""))
            sv += ["v(op%s)" % n, "v(on%s)" % n, "v(x%s.dip)" % n, "v(x%s.din)" % n]
        sv.append("i(v_%s)" % v)
    L += [".control", "set num_threads=1", "save " + " ".join(sv) + " v(clk) i(vdd)",
          "tran 5p 70n 0 20p", "write @RAW@/cmp_tran.raw", ".endc", ".end"]
    open(os.path.join(HERE, "tb_cmp3_tran%s.cir" % ("" if SET == "a" else "_" + SET)), "w").write("\n".join(L) + "\n")


def noise():
    L = ["* tb_cmp3_noise.cir (generated by sim/r3/gen_cmp3_decks.py) -- r1_cmp3 first stage, quasi-static noise"] + HDR
    L += ["Vdd vdd 0 @VDD@", "Vclkb clkb 0 0", "Vx vx 0 @VX@"]
    ctl = [".control", "set num_threads=1", "set wr_singlescale", "set wr_vecnames"]
    for v in VARIANTS:
        L.append(bias(v, "vdd"))
        L.append("Vinp%s inp%s 0 DC @VCM@ AC 1" % (v, v))
        L.append("Vinn%s inn%s 0 DC @VCM@" % (v, v))
        L.append("X%s inp%s inn%s dp%s dn%s clkb vbp%s vdd 0 r1_cmp3_s1 %s" % (v, v, v, v, v, v,
                 VARIANTS[v][2] if len(VARIANTS[v]) > 2 else ""))
        L.append("Vdp%s dp%s vx 0" % (v, v))
        L.append("Vdn%s dn%s vx 0" % (v, v))
        L.append("H%s out%s 0 poly(2) Vdp%s Vdn%s 0 1 -1" % (v, v, v, v))
    for v in VARIANTS:
        ctl += ["op", "print i(vdp%s) i(vdn%s) v(vbp%s)" % (v, v, v),
                "noise v(out%s) vinp%s dec 20 1e3 1e11" % (v, v), "setplot noise1",
                "wrdata @RAW@/noise_%s.txt inoise_spectrum onoise_spectrum" % v, "destroy all", "reset"]
    L += ctl + [".endc", ".end"]
    open(os.path.join(HERE, "tb_cmp3_noise%s.cir" % ("" if SET == "a" else "_" + SET)), "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    tran()
    noise()
    print("wrote tb_cmp3_tran.cir, tb_cmp3_noise.cir")
