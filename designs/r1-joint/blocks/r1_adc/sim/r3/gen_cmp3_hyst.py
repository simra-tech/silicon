#!/usr/bin/env python3
"""Write sim/r3/tb_cmp3_hyst.cir: comparator memory (hysteresis) test with the revision-3 decision clock.
Found necessary after r3-ref-tt-*-c: the chosen r80b comparator (2 x ~2 pF integration capacitors, reset NMOS
2 um) decided wrongly with inputs up to 18 mV of the opposite sign to the previous decision, because the 3.2 ns
reset does not discharge dip/din (the transient deck tb_cmp3_tran.cir used a constant input and could not see it).
Input per decision period alternates: +A_big, -A_small, +A_big, -A_small, ... (A_big 30 mV, A_small @ASM@);
the decision on every -A_small period must be 0. Variants: reset width wr. CM 0.6 / 0.35 / 0.1 V.
"""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
H = 1000 / 60.0
WR = ["2u", "8u", "16u", "24u"]
# set d (after set c showed that wcap 80u does not decide in 13 ns once the input alternates):
# name -> (wcap, rbl, wr)
SETD = {"c16": ("16u", "120u", "4u"), "c24": ("24u", "120u", "6u"), "c32": ("32u", "120u", "8u"),
        "c32c": ("32u", "160u", "8u"), "c40b": ("40u", "120u", "8u"), "c40c": ("40u", "160u", "8u")}
SET = os.environ.get("HYST_SET", "c")
L = ["* tb_cmp3_hyst.cir (generated by sim/r3/gen_cmp3_hyst.py) -- r1_cmp3 (wcap 80u, rbl 85u) memory test",
     ".lib /foss/pdks/ihp-sg13g2/libs.tech/ngspice/models/cornerMOSlv.lib @CORNER@",
     ".lib /foss/pdks/ihp-sg13g2/libs.tech/ngspice/models/cornerCAP.lib cap_typ",
     ".lib /foss/pdks/ihp-sg13g2/libs.tech/ngspice/models/cornerRES.lib res_typ",
     ".include schematic/r1_adc_r3.spice", ".temp @TEMP@",
     ".option reltol=1e-4 vntol=1e-7 abstol=1e-13 method=gear", "Vdd vdd 0 @VDD@",
     "Vclk clk 0 PULSE(0 @VDD@ 1n 50p 50p 13.45n %.6gn)" % H,
     "Vclkb clkb 0 PULSE(@VDD@ 0 1n 50p 50p 13.45n %.6gn)" % H,
     # differential input: +30 mV in even periods, -A_small in odd periods; changes in the reset phase
     "Vd vd 0 PULSE(0.03 -@ASM@ %.6gn 0.2n 0.2n %.6gn %.6gn)" % (H - 1.5, H - 0.4, 2 * H),
     ]
sv = ["v(clk)", "v(vd)"]
VARS = [(w.rstrip("u"), "80u", "85u", w) for w in WR] if SET == "c" else [(k,) + v for k, v in SETD.items()]
for nm, wc, rb, w in VARS:
    L.append("XB%s vbp%s vdd 0 r1_cmp3_bias rbl=%s" % (nm, nm, rb))   # one bias per three comparators, as in the ADC (two)
    for cm, tag in ((0.6, "h"), (0.35, "m"), (0.1, "l")):
        n = "w%s%s" % (nm, tag)
        L.append("B%sp inp%s 0 v=%g+v(vd)/2" % (n, n, cm))
        L.append("B%sn inn%s 0 v=%g-v(vd)/2" % (n, n, cm))
        L.append("X%s inp%s inn%s clk clkb op%s on%s vbp%s vdd 0 r1_cmp3 wr=%s wcap=%s" % (n, n, n, n, n, nm, w, wc))
        sv += ["v(op%s)" % n, "v(on%s)" % n]
L += [".control", "set num_threads=1", "save " + " ".join(sv), "tran 5p %.6gn 0 20p" % (12 * H), "write @RAW@/hyst.raw", ".endc", ".end"]
open(os.path.join(HERE, "tb_cmp3_hyst%s.cir" % ("" if SET == "c" else "_" + SET)), "w").write("\n".join(L) + "\n")
print("wrote tb_cmp3_hyst.cir")
