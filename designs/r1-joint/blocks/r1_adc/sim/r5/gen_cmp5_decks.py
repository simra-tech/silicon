#!/usr/bin/env python3
"""Write the revision-5 decision-0 comparator decks (sim/r5/tb_cmp5n_mem.cir, sim/r5/tb_cmp5n_noise.cir).

Question (revision 5, item 2): which r1_cmp5n (NMOS-input) sizing resolves decision 0 at the 0.6 V input CM at
tt, ss / 125 C / 1.08 V and ff / -40 C / 1.32 V inside the 33 ns tick (strobe at the next clk30 edge - 0.6 ns), and
what is its input noise at ss / 125 C. Clock as in revision 4: ideal clk30 -> r1_cmp4_clkgen -> smooth buffer.
mem deck: per tick +30 mV, then -@ASM@ (memory and decision-time test of revision 4), CM 0.70 / 0.60 / 0.50 V
(AFE output CM 0.594-0.597 V, isense 0.57 V, margin both ways). In the ADC the comparator makes one decision per
conversion after a long reset, so this test is harder than the use.
noise deck: first stage r1_cmp5n_s1 only, dip/din held at @VX@, quasi-static .noise (method A of revision 2).
Variants: name -> dict of instance parameters; 'sw' = tail current source gate tied to VDD (switch-only tail).
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
T = 1000 / 30.0      # ns
SETS = {"b": {"n8": {}, "n8s": {"sw": 1}, "n8c": {"wcap": "10u"},
              "n16": {"wi": "16u", "ngi": 4, "wt": "8u", "wtc": "8u", "wcap": "40u", "wr": "8u", "wh": "8u"}},
        # set c (after set b: memory errors with large integration capacitors and a weak reset; noise > 60 uV at ss
        # with the short integration of set b): stronger reset, half the tail current, smaller caps
        "c": {"n16r": {"wi": "16u", "ngi": 4, "wt": "8u", "wtc": "4u", "wcap": "40u", "wr": "16u", "wh": "8u"},
              "n16c": {"wi": "16u", "ngi": 4, "wt": "8u", "wtc": "8u", "wcap": "20u", "wr": "8u", "wh": "8u"},
              "n12r": {"wi": "12u", "ngi": 3, "wt": "6u", "wtc": "3u", "wcap": "30u", "wr": "16u", "wh": "8u"},
              "n16rl": {"wi": "16u", "li": "0.5u", "ngi": 4, "wt": "8u", "wtc": "4u", "wcap": "30u", "wr": "16u", "wh": "8u"}}}
SET = os.environ.get("CMP5_SET", "b")
VARIANTS = SETS[SET]
SFX = "" if SET == "b" else "_" + SET
CMS = ((0.70, "h"), (0.60, "m"), (0.50, "l"))
HDR = [".lib /foss/pdks/ihp-sg13g2/libs.tech/ngspice/models/cornerMOSlv.lib @CORNER@",
       ".lib /foss/pdks/ihp-sg13g2/libs.tech/ngspice/models/cornerCAP.lib cap_typ",
       ".lib /foss/pdks/ihp-sg13g2/libs.tech/ngspice/models/cornerRES.lib res_typ",
       ".include schematic/r1_adc_r5.spice", ".temp @TEMP@"]
NT = 10


def prm(v, s1=False):
    keys = ("wi", "li", "ngi", "wt", "wtc", "ltc") if s1 else ("wi", "li", "ngi", "wt", "wtc", "ltc", "wcap", "lcap", "wr", "wh", "wlp", "wlt")
    return " ".join("%s=%s" % (k, x) for k, x in VARIANTS[v].items() if k in keys)


def mem():
    L = ["* tb_cmp5n_mem.cir (generated by sim/r5/gen_cmp5_decks.py) -- r1_cmp5n variants, one decision per tick,"
         " clock from r1_cmp4_clkgen, alternating +30 mV / -ASM input"] + HDR
    L += [".option reltol=1e-4 vntol=1e-7 abstol=1e-13 method=gear", "Vdd vdd 0 @VDD@",
          "Vclk30 clk30 0 PULSE(0 @VDD@ 2n 50p 50p %.6gn %.6gn)" % (T / 2 - 0.05, T),
          "XCKG clk30 mclk mclkb vdd 0 r1_cmp4_clkgen",
          "Bclk clk 0 v=@VDD@*0.5*(1+tanh(25*(v(mclk)-0.6)))",
          "Bclkb clkb 0 v=@VDD@*0.5*(1-tanh(25*(v(mclk)-0.6)))",
          "Vd vd 0 PULSE(0.03 -@ASM@ %.6gn 0.2n 0.2n %.6gn %.6gn)" % (2 + T - 1.2, T - 0.2, 2 * T)]
    sv = ["v(clk30)", "v(mclk)", "v(vd)", "i(vdd)"]
    for v in VARIANTS:
        L.append("V_%s vdd_%s vdd 0" % (v, v))
        if VARIANTS[v].get("sw"):
            L.append("Vbn%s vbn%s 0 @VDD@" % (v, v))
        else:
            L.append("XB%s vbn%s vdd_%s 0 r1_cmp5n_bias" % (v, v, v))
        for cm, tag in CMS:
            n = "%s%s" % (v, tag)
            L.append("Bp%s ip%s 0 v=%g+v(vd)/2" % (n, n, cm))
            L.append("Bn%s in%s 0 v=%g-v(vd)/2" % (n, n, cm))
            L.append("X%s ip%s in%s clk clkb op%s on%s vbn%s vdd_%s 0 r1_cmp5n %s" % (n, n, n, n, n, v, v, prm(v)))
            sv += ["v(op%s)" % n, "v(on%s)" % n]
        sv.append("i(v_%s)" % v)
    L += [".control", "set num_threads=1", "save " + " ".join(sv),
          "tran 5p %.6gn 0 20p" % (2 + NT * T), "write @RAW@/mem.raw", ".endc", ".end"]
    open(os.path.join(HERE, "tb_cmp5n_mem%s.cir" % SFX), "w").write("\n".join(L) + "\n")


def noise():
    L = ["* tb_cmp5n_noise.cir (generated by sim/r5/gen_cmp5_decks.py) -- r1_cmp5n first stage, quasi-static noise"] + HDR
    L += ["Vdd vdd 0 @VDD@", "Vclk clk 0 @VDD@", "Vx vx 0 @VX@"]
    ctl = [".control", "set num_threads=1", "set wr_singlescale", "set wr_vecnames"]
    for v in VARIANTS:
        if VARIANTS[v].get("sw"):
            L.append("Vbn%s vbn%s 0 @VDD@" % (v, v))
        else:
            L.append("XB%s vbn%s vdd 0 r1_cmp5n_bias" % (v, v))
        L.append("Vinp%s inp%s 0 DC @VCM@ AC 1" % (v, v))
        L.append("Vinn%s inn%s 0 DC @VCM@" % (v, v))
        L.append("X%s inp%s inn%s dp%s dn%s clk vbn%s vdd 0 r1_cmp5n_s1 %s" % (v, v, v, v, v, v, prm(v, True)))
        L.append("Vdp%s vx dp%s 0" % (v, v))
        L.append("Vdn%s vx dn%s 0" % (v, v))
        L.append("H%s out%s 0 poly(2) Vdp%s Vdn%s 0 1 -1" % (v, v, v, v))
    for v in VARIANTS:
        ctl += ["op", "noise v(out%s) vinp%s dec 20 1e3 1e11" % (v, v), "setplot noise1",
                "wrdata @RAW@/noise_%s.txt inoise_spectrum onoise_spectrum" % v, "destroy all", "reset"]
    L += ctl + [".endc", ".end"]
    open(os.path.join(HERE, "tb_cmp5n_noise%s.cir" % SFX), "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    mem()
    noise()
    print("wrote tb_cmp5n_mem%s.cir, tb_cmp5n_noise%s.cir" % (SFX, SFX))
