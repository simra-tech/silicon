#!/usr/bin/env python3
"""Write sim/r1_adc_timing.inc: ideal timing sources standing in for r1_ctrl (30 MHz, 30-cycle frame of 1 us).

Frame f starts at t0 + f*1us with the falling edge of trk (the common sampling edge of both slices).
Cycles 0-11: decisions of slice A, 12-23: slice B, 24-29: track (trk = rst = 1).
Comparator evaluates while mclk = 1 (first half of each cycle, starting 2 ns into the cycle); decision k
is captured by stb_k 0.4 T after the start of evaluation; the output latch strobe lat follows decision 23.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
T = 1.0 / 30e6
F = 30 * T
T0 = 250e-9
TR = 50e-12
D = 2e-9


def main():
    L = ["* r1_adc_timing.inc (generated by gen_timing.py) -- IDEAL timing sources (stand-in for r1_ctrl)",
         "* T = %.6g s (30 MHz), frame = %.6g s, first sampling edge t0 = %.6g s" % (T, F, T0),
         ".param t_cyc=%.9g t_frame=%.9g t_0=%.9g" % (T, F, T0)]
    L.append("Vtrk trk_enc 0 PULSE(0 1.2 %.9g %g %g %.9g %.9g)" % (T0 - 6 * T, TR, TR, 6 * T - TR, F))
    L.append("Vmclk mclk 0 PULSE(0 1.2 %.9g %g %g %.9g %.9g)" % (T0 + D, TR, TR, T / 2 - TR, T))
    L.append("Vwina wina 0 PULSE(0 1.2 %.9g %g %g %.9g %.9g)" % (T0, TR, TR, 12 * T - TR, F))
    L.append("Vwinb winb 0 PULSE(0 1.2 %.9g %g %g %.9g %.9g)" % (T0 + 12 * T, TR, TR, 12 * T - TR, F))
    for k in range(24):
        L.append("Vstb%d stb%d 0 PULSE(0 1.2 %.9g %g %g %.9g %.9g)" % (k, k, T0 + k * T + D + 0.4 * T, TR, TR, 2e-9, F))
    L.append("Vlat lat 0 PULSE(0 1.2 %.9g %g %g %.9g %.9g)" % (T0 + 23.4 * T + D + 5e-9, TR, TR, 2e-9, F))
    with open(os.path.join(HERE, "r1_adc_timing.inc"), "w") as f:
        f.write("\n".join(L) + "\n")
    print("wrote r1_adc_timing.inc")


if __name__ == "__main__":
    main()
