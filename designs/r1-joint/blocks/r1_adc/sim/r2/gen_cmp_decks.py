#!/usr/bin/env python3
"""Write the revision-2 comparator decks (sim/r2/tb_cmp2_tran.cir, sim/r2/tb_cmp2_noise.cir).

tran:  every variant at two input common modes (0.6 V = first decision, 0.1 V = last decisions), +0.2 mV input,
       30 MHz clock as in the ADC (evaluate 16.6 ns). Gives integration time, decision time, energy per decision.
noise: first stage r1_cmp2_s1 only, tail on, dip/din held at VX by 0 V sources; output = i(dip) - i(din) through a
       CCVS; .noise referred to the differential input. Method: quasi-static PSD at the integration operating point,
       integrated with the |sinc(pi f T_int)|^2 window of an integrator of length T_int (post_cmp2.py).
"""
import os
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from cmp_variants import VARIANTS, inst

HERE = os.path.dirname(os.path.abspath(__file__))
HDR = [".lib /foss/pdks/ihp-sg13g2/libs.tech/ngspice/models/cornerMOSlv.lib @CORNER@",
       ".lib /foss/pdks/ihp-sg13g2/libs.tech/ngspice/models/cornerCAP.lib cap_typ",
       ".lib /foss/pdks/ihp-sg13g2/libs.tech/ngspice/models/cornerMOShv.lib @CORNER@",
       ".lib /foss/pdks/ihp-sg13g2/libs.tech/ngspice/models/cornerRES.lib res_typ",
       ".include schematic/r1_adc_r2.spice", ".temp @TEMP@"]


def tran():
    L = ["* tb_cmp2_tran.cir (generated by sim/r2/gen_cmp_decks.py) -- r1_cmp2 variants, decision dynamics"] + HDR
    L += [".option reltol=1e-4 vntol=1e-7 abstol=1e-13 method=gear",
          "Vdd vdd 0 @VDD@",
          "Vclk clk 0 PULSE(0 @VDD@ 2n 50p 50p 16.6167n 33.3333n)",
          "Vclkb clkb 0 PULSE(@VDD@ 0 2n 50p 50p 16.6167n 33.3333n)", "XB vbp vdd 0 r1_cmp2_bias ib=@IB@"]
    sv = []
    for v in VARIANTS:
        for cm, tag in ((0.6, "h"), (0.35, "m"), (0.1, "l")):
            n = "%s%s" % (v, tag)
            L.append("Vp%s ip%s 0 %g" % (n, n, cm + 1e-4))
            L.append("Vn%s in%s 0 %g" % (n, n, cm - 1e-4))
            L.append("X%s ip%s in%s clk clkb op%s on%s vbp vdd 0 r1_cmp2 %s" % (n, n, n, n, n, inst(v)))
            sv += ["v(op%s)" % n, "v(on%s)" % n, "v(x%s.dip)" % n, "v(x%s.din)" % n]
    L += [".control", "set num_threads=1", "save " + " ".join(sv) + " v(clk) i(vdd)",
          "tran 5p 100n 0 20p", "write @RAW@/cmp_tran.raw", ".endc", ".end"]
    open(os.path.join(HERE, "tb_cmp2_tran.cir"), "w").write("\n".join(L) + "\n")


def noise():
    L = ["* tb_cmp2_noise.cir (generated by sim/r2/gen_cmp_decks.py) -- r1_cmp2 first stage, quasi-static noise"] + HDR
    L += ["Vdd vdd 0 @VDD@", "Vclkb clkb 0 0", "Vx vx 0 @VX@", "XB vbp vdd 0 r1_cmp2_bias ib=@IB@"]
    ctl = [".control", "set num_threads=1", "set wr_singlescale", "set wr_vecnames"]
    for v in VARIANTS:
        p = VARIANTS[v]
        L.append("Vinp%s inp%s 0 DC @VCM@ AC 1" % (v, v))
        L.append("Vinn%s inn%s 0 DC @VCM@" % (v, v))
        L.append("X%s inp%s inn%s dp%s dn%s clkb vbp vdd 0 r1_cmp2_s1 wi=%s li=%s ngi=%s wt=%s wtc=%s ltc=%s"
                 % (v, v, v, v, v, p["wi"], p["li"], p["ngi"], p["wt"], p["wtc"], p["ltc"]))
        L.append("Vdp%s dp%s vx 0" % (v, v))
        L.append("Vdn%s dn%s vx 0" % (v, v))
        L.append("H%s out%s 0 poly(2) Vdp%s Vdn%s 0 1 -1" % (v, v, v, v))
    for v in VARIANTS:
        ctl += ["op", "print i(vdp%s) i(vdn%s)" % (v, v),
                "ac lin 1 100e6 100e6",
                "let cin_%s = abs(imag(i(vinp%s)))/(2*3.14159265*100e6)" % (v, v),
                "let gm_%s = abs(real(v(out%s)))" % (v, v),
                "print cin_%s gm_%s" % (v, v),
                "noise v(out%s) vinp%s dec 20 1e3 1e11" % (v, v),
                "setplot noise1",
                "wrdata @RAW@/noise_%s.txt inoise_spectrum onoise_spectrum" % v,
                "destroy all", "reset"]
    ctl += [".endc", ".end"]
    open(os.path.join(HERE, "tb_cmp2_noise.cir"), "w").write("\n".join(L + ctl) + "\n")


if __name__ == "__main__":
    tran()
    noise()
    print("wrote tb_cmp2_tran.cir tb_cmp2_noise.cir")
