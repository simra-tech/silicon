#!/usr/bin/env python3
"""Write sim/r2/r1_adc_timing_r2.inc: ideal timing sources standing in for r1_ctrl, revision 2 (13 decisions).

Frame f (1 us = 30 cycles of 30 MHz) starts at T0 + f*1us with the common falling edge of trka0 and trkb0
(sampling instant of both slices). Slice A decides in cycles 0-12 (stb0..stb12), latches at lata, and tracks
again from cycle 13 (trka0 high 13 T + 1 ns .. 30 T). Slice B decides in cycles 13-25 (stb13..stb25), latches at
latb and tracks in cycles 26-29 (trkb0 high 26 T + 1 ns .. 30 T, 132 ns). Comparator evaluates while mclk = 1
(first half of each cycle, from 2 ns); decision k is captured by stb_k 0.45 T after the start of evaluation.
adc_done for slice A = lata (12.66 T after the edge) -> conversion 13 ticks, done in tick 13 (<= 15, INTERFACES).
T0 = 0.6 us so that the first frame has a full slice-A track window. Current-channel decks write their own
trka1/trkb1 sources (is_smp_a/b); here trka1 = trkb1 = 0.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
T = 1.0 / 30e6
F = 30 * T
T0 = 600e-9
TR = 50e-12
D = 2e-9
ND = 13


def lines(vdd=1.2):
    L = ["* r1_adc_timing_r2.inc (generated by gen_timing_r2.py) -- IDEAL timing sources (stand-in for r1_ctrl)",
         "* T = %.6g s (30 MHz), frame = %.6g s, first sampling edge t0 = %.6g s" % (T, F, T0),
         ".param t_cyc=%.9g t_frame=%.9g t_0=%.9g" % (T, F, T0)]
    hi = vdd
    L.append("Vtrka0 trka0 0 PULSE(0 %g %.9g %g %g %.9g %.9g)" % (hi, T0 - 17 * T + 1e-9, TR, TR, 17 * T - 1e-9 - TR, F))
    L.append("Vtrkb0 trkb0 0 PULSE(0 %g %.9g %g %g %.9g %.9g)" % (hi, T0 - 4 * T + 1e-9, TR, TR, 4 * T - 1e-9 - TR, F))
    L.append("Vmclk mclk 0 PULSE(0 %g %.9g %g %g %.9g %.9g)" % (hi, T0 + D, TR, TR, T / 2 - TR, T))
    L.append("Vwina wina 0 PULSE(0 %g %.9g %g %g %.9g %.9g)" % (hi, T0, TR, TR, ND * T - TR, F))
    L.append("Vwinb winb 0 PULSE(0 %g %.9g %g %g %.9g %.9g)" % (hi, T0 + ND * T, TR, TR, ND * T - TR, F))
    for k in range(2 * ND):
        L.append("Vstb%d stb%d 0 PULSE(0 %g %.9g %g %g %.9g %.9g)" % (k, k, hi, T0 + k * T + D + 0.45 * T, TR, TR, 2e-9, F))
    L.append("Vlata lata 0 PULSE(0 %g %.9g %g %g %.9g %.9g)" % (hi, T0 + (ND - 1) * T + D + 0.45 * T + 5e-9, TR, TR, 2e-9, F))
    L.append("Vlatb latb 0 PULSE(0 %g %.9g %g %g %.9g %.9g)" % (hi, T0 + (2 * ND - 1) * T + D + 0.45 * T + 5e-9, TR, TR, 2e-9, F))
    return L


def main():
    for tag, vdd in (("", 1.2), ("_vdd108", 1.08), ("_vdd132", 1.32)):
        with open(os.path.join(HERE, "r1_adc_timing_r2%s.inc" % tag), "w") as f:
            f.write("\n".join(lines(vdd)) + "\n")
    print("wrote r1_adc_timing_r2*.inc")


if __name__ == "__main__":
    main()
