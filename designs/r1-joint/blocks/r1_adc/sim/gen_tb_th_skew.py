#!/usr/bin/env python3
"""Write sim/tb_th_skew_<tag>.cir: sampling skew between the two track-and-hold slices.

Each copy holds two full r1_th slices (A: SIN path, B: COS path; complete bootstrapped switches on both mux
inputs, transistor bottom-plate drivers held in the sampling state) driven by one common trk_enc edge, as on
the chip. Both slices see the same differential ramp vd(t) = V0 + S*(t - t_edge), S = +/-20 mV/ns, for t > t_edge - 20 ns (constant
before, clipped to +/-1.15 V so that no input leaves the rails), through the
SIN and COS inputs; t_edge is the 50 % point of the ideal trk_enc falling edge. The held differential top-plate
voltage, read 10 ns after the edge, gives the effective sampling instant t_eff = (v_held - V0)/S relative to
t_edge for each slice; skew = t_eff(A) - t_eff(B). Comparators are not connected (top plates only).

usage: gen_tb_th_skew.py nominal | mc <n> [seedless: every copy draws its own MOS mismatch, mm_ok=1]
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
NB = 11
T_EDGE = 200e-9
S = 20e-3 / 1e-9


def main():
    mode = sys.argv[1]
    if mode == "nominal":
        copies = [(v0, s) for v0 in (-0.7, -0.35, 0.0, 0.35, 0.7) for s in (S, -S)]
        lib, mm, sect, tag = "r1_adc.spice", None, "mos_tt", "nominal"
    else:
        n = int(sys.argv[2])
        copies = [(0.0 if i % 2 == 0 else 0.7, S) for i in range(n)]
        lib, mm, sect, tag = "r1_adc_mm.spice", 1, "mos_tt_mismatch", "mc%d" % n
    L = ["* tb_th_skew_%s.cir (generated by gen_tb_th_skew.py) -- T/H sampling skew, %d copies" % (tag, len(copies)),
         ".lib /foss/pdks/ihp-sg13g2/libs.tech/ngspice/models/cornerMOSlv.lib %s" % sect,
         ".lib /foss/pdks/ihp-sg13g2/libs.tech/ngspice/models/cornerCAP.lib cap_typ"]
    if mm is not None:
        L.append(".param mmos=1")
    L += [".include schematic/%s" % lib,
          ".temp 27",
          ".option reltol=1e-4 vntol=1e-7 abstol=1e-13 method=trap",
          "Vdd vdd 0 1.2", "Vref vref 0 1.2",
          "* common track signal: hold 0-30 ns (boost capacitors charge), track 30 ns - t_edge (170 ns, as in the",
          "* ADC frame), 50 ps fall at t_edge; distributed from one r1_ctrl output",
          "Vtrk trk 0 PWL(0 0 30n 0 30.05n 1.2 %.6g 1.2 %.6g 0)" % (T_EDGE - 25e-12, T_EDGE + 25e-12),
          "Vz z 0 0", "Vcm cm 0 0.6"]
    zeros = " ".join(["z"] * (2 * NB))
    for i, (v0, s) in enumerate(copies):
        L.append("* copy %d: V0 = %g V, S = %g V/s" % (i, v0, s))
        L.append("Bx%d x%d 0 v=min(max(%g+%g*max(time-%g,-20n),-1.15),1.15)" % (i, i, v0, s, T_EDGE))
        L.append("Bp%d ip%d 0 v=0.6+v(x%d)/2" % (i, i, i))
        L.append("Bn%d in%d 0 v=0.6-v(x%d)/2" % (i, i, i))
        for sl in ("a", "b"):
            L.append("XTH%s%d ip%d in%d cm cm trk z t%sp%d t%sn%d %s vdd vref 0 r1_th" % (sl, i, i, i, sl, i, sl, i, zeros))
            L.append("Cc%sp%d t%sp%d 0 30f" % (sl, i, sl, i))
            L.append("Cc%sn%d t%sn%d 0 30f" % (sl, i, sl, i))
    L.append("* 30 fF per top node: comparator input load (r1_cmp input pair gate, estimated)")
    L.append(".control")
    L.append("set num_threads=1")
    L.append("tran 10p %.6g 0 20p" % (T_EDGE + 12e-9))
    for i in range(len(copies)):
        for sl in ("a", "b"):
            L.append("let v%s%d = v(t%sp%d) - v(t%sn%d)" % (sl, i, sl, i, sl, i))
            L.append("meas tran h%s%d find v%s%d at=%.6g" % (sl, i, sl, i, T_EDGE + 10e-9))
            L.append("meas tran d%s%d find v%s%d at=%.6g" % (sl, i, sl, i, T_EDGE + 10.5e-9))
    L.append("write @RAW@/tb.raw")
    L.append(".endc")
    L.append(".end")
    with open(os.path.join(HERE, "tb_th_skew_%s.cir" % tag), "w") as f:
        f.write("\n".join(L) + "\n")
    with open(os.path.join(HERE, "tb_th_skew_%s.copies" % tag), "w") as f:
        for v0, s in copies:
            f.write("%g %g\n" % (v0, s))
    print("wrote tb_th_skew_%s.cir" % tag)


if __name__ == "__main__":
    main()
